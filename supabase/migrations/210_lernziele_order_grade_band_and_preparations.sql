  n integer;
BEGIN
  FOR p IN SELECT id FROM projects WHERE slug IN ('evomentor-thuringia', 'evomentor-thuringia-sandbox') LOOP
    SELECT count(*) INTO n FROM lpm_data_objects WHERE project_id = p AND status = 'accepted' AND grade_band IN ('5/6', '7/8', '7', '8');
    IF n = 0 THEN
      CONTINUE;
    END IF;
    IF (SELECT count(*) FROM lpm_data_objects WHERE project_id = p AND status = 'accepted' AND grade_band = '5/6' AND curriculum_sequence >= 0 AND curriculum_sequence < 174) <> 174
       OR (SELECT count(DISTINCT curriculum_sequence) FROM lpm_data_objects WHERE project_id = p AND status = 'accepted' AND grade_band = '5/6') <> 174 THEN
      RAISE EXCEPTION '210: the grade 5/6 goals of project % are not numbered 0 to 173', p;
    END IF;
