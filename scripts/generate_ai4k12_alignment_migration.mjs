#!/usr/bin/env node
// Generates the migration that aligns Computational-Core and Interdisciplinary with AI4K12 (held in CompetencyBase).
//
//   node scripts/generate_ai4k12_alignment_migration.mjs scripts/data/ai4k12-alignment.json > supabase/migrations/<n>_ai4k12_alignment.sql
//
// What it writes, all AI-drafted and unreviewed:
//   1. AI4K12 items as competency schema elements of each space (status proposed): the Big Idea, the concept row and the learning
//      objective or enduring understanding of a band, joined by parent_id. Only items that a stage or concept aligns with, and the
//      items that fall inside the space's focus and have no stage (alignment_state 'gap'), become elements.
//   2. Stage-to-item tags in lpm_object_tags with role '<relation>-<strength>'. The reason for each pair and any difference in the
//      sense of a shared word are kept in the element's metadata.aligned_stages.
//   3. For concepts of the space that align with an AI4K12 concept row, an additive metadata.ai4k12_alignment on the concept.
//   4. One paragraph in each introduction that states the focus (narrow computer science for Computational-Core, cross-domain
//      for Interdisciplinary) and how far the alignment goes.
// Input: the reviewed alignment file (stage alignments, concept alignments, gaps), the AI4K12 records read from CompetencyBase and
// the stage references. Project and concept ids are read live (service_role key from .supabase-secrets). Ids are uuid5-derived.
// AI4K12 content is CC BY-NC-SA 4.0 (AI4K12 Initiative, AAAI and CSTA, NSF DRL-1846073), used here with attribution.

import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const input = JSON.parse(readFileSync(path.resolve(process.argv[2]), 'utf8'))
const env = readFileSync(path.join(root, '.env.local'), 'utf8')
const URL_ = env.match(/VITE_SUPABASE_URL=(.*)/)[1].trim().replace(/^"|"$/g, '')
const KEY = readFileSync(path.join(root, '.supabase-secrets', 'service-role-key.txt'), 'utf8').trim()
async function rest(p) {
  const r = await fetch(`${URL_}/rest/v1/${p}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
  if (!r.ok) throw new Error(`${p}: ${r.status}`)
  return r.json()
}
const NS = uuid5('https://openevo-ccs.github.io/openlpm/ai4k12-alignment-2026-10-26', uuid5.URL)
const uid = (...parts) => uuid5(parts.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const NOTE = 'AI-drafted on 2026-10-26 by comparing the stages and concepts of the space with the AI4K12 grade band progression charts in CompetencyBase. No subject-matter expert has reviewed it.'
const CITE = 'AI4K12 Initiative (2020-2022). Five Big Ideas in Artificial Intelligence, Grade Band Progression Charts. AAAI and CSTA, NSF DRL-1846073. CC BY-NC-SA 4.0. https://ai4k12.org/gradeband-progression-charts/'
const SPACES = {
  comp: { slug: 'computational-core-lpm-synth', name: 'Computational-Core', focus: 'a narrow computer science focus: only technical content (representation, data, search, models, training, datasets and program behaviour) is aligned, and societal, ethical and cognitive items are left to the Interdisciplinary space' },
  int: { slug: 'interdisciplinary-lpm-synth', name: 'Interdisciplinary', focus: 'a cross-domain focus: all five Big Ideas can be reached, and each alignment says what the reading across biology, culture, technology, education, AI and computation, and cognition adds' },
}
const R = input.records
const KIND_LABEL = { bigidea: 'Big Idea', concept: 'concept', LO: 'objective', EU: 'understanding' }
const labelOf = (id) => {
  const r = R[id]
  if (r.kind === 'bigidea') return `AI4K12 Big Idea: ${r.statement}`
  if (r.kind === 'concept') return `AI4K12 ${r.code}: ${r.statement}`
  return `AI4K12 ${r.code.replace(/\.(LO|EU)$/, '')}, ${r.band}, ${KIND_LABEL[r.kind]}`
}
const lines = []
const w = (s = '') => lines.push(s)
const stats = {}
const warnings = []
w(`-- Alignment of Computational-Core and Interdisciplinary with AI4K12.
-- Generated by scripts/generate_ai4k12_alignment_migration.mjs; do not hand-edit.
--
-- AI4K12 items become competency elements (status proposed) of each space, stages are tagged with the items they align with,
-- concepts carry their concept-row alignments in metadata, and each introduction gets one paragraph that states the focus.
-- Computational-Core is aligned with a narrow computer science focus. Interdisciplinary is aligned with a richer cross-domain focus.
-- Everything is AI-drafted and unreviewed. AI4K12 content is CC BY-NC-SA 4.0 (see each element's metadata for the citation).
-- Rollback: DELETE FROM lpm_schema_elements WHERE element_type = 'competency' AND metadata->>'source_vocabulary' = 'AI4K12'
--           AND project_id IN (SELECT id FROM projects WHERE slug IN ('computational-core-lpm-synth', 'interdisciplinary-lpm-synth'));
--           (tags go by cascade). The concept metadata is removed with: UPDATE lpm_schema_elements SET metadata = metadata - 'ai4k12_alignment' WHERE metadata ? 'ai4k12_alignment'.

SET search_path = public, extensions;
`)
for (const [key, sp] of Object.entries(SPACES)) {
  const al = input.alignments[key]
  const [project] = await rest(`projects?select=id&slug=eq.${sp.slug}`)
  const els = await rest(`lpm_schema_elements?select=id,label,metadata&project_id=eq.${project.id}&element_type=eq.concept&limit=1000`)
  const conceptEl = new Map(els.filter((e) => !e.metadata?.level || ['organizing', 'extension'].includes(e.metadata.level)).map((e) => [e.label, e]))
  // Which items become elements, and what each carries
  const aligned = new Map() // id -> [{stage ref, relation, strength, why, senseDiffers, adjacentBand}]
  for (const sa of al.stageAlignments) for (const it of sa.items) {
    if (!aligned.has(it.id)) aligned.set(it.id, [])
    aligned.get(it.id).push({ ref: sa.stage, ...it })
  }
  const gaps = new Map(al.ai4k12Unaligned.map((g) => [g.id, g.why]))
  const conceptItems = new Set(al.conceptAlignments.flatMap((c) => c.items))
  const wanted = new Set([...aligned.keys(), ...gaps.keys(), ...conceptItems])
  const withParents = new Set()
  for (const id of wanted) { let cur = id; while (cur) { withParents.add(cur); cur = R[cur]?.broader } }
  for (const id of withParents) if (!R[id]) throw new Error(`${key}: unknown AI4K12 id ${id}`)
  const order = [...withParents].sort((a, b) => ({ bigidea: 0, concept: 1, LO: 2, EU: 2 }[R[a].kind] - { bigidea: 0, concept: 1, LO: 2, EU: 2 }[R[b].kind]) || R[a].code.localeCompare(R[b].code))
  w(`-- ${sp.name}: ${order.length} AI4K12 elements (${aligned.size} aligned items, ${[...gaps.keys()].filter((g) => !aligned.has(g)).length} gaps)`)
  let nTags = 0
  for (const id of order) {
    const r = R[id]
    const pairs = (aligned.get(id) ?? []).map((a) => ({ stage_id: input.stageRefs[`${key}|${a.ref}`].id, stage: `${a.ref} ${input.stageRefs[`${key}|${a.ref}`].title}`, relation: a.relation, strength: a.strength, why: a.why, sense_differs: a.senseDiffers ?? null, adjacent_band: !!a.adjacentBand }))
    const state = pairs.length ? 'aligned' : gaps.has(id) ? 'gap' : 'structure'
    const meta = { level: 'ai4k12', source_vocabulary: 'AI4K12', competencybase_id: id, human_coding_scheme: r.code, kind: r.kind, band: r.band, definition: r.statement, alignment_state: state, aligned_stages: pairs, ...(state === 'gap' ? { gap_note: gaps.get(id) } : {}), citation: CITE, proposed_on: '2026-10-26', focus: key === 'comp' ? 'computer-science' : 'cross-domain', draft_note: NOTE }
    const parent = r.broader ? uid('element', key, r.broader) : null
    w('INSERT INTO lpm_schema_elements (id, project_id, element_type, label, definition, parent_id, metadata, status)')
    w(`VALUES (${q(uid('element', key, id))}, ${q(project.id)}, 'competency', ${q(labelOf(id))}, ${q(r.statement)}, ${parent ? q(parent) : 'NULL'}, ${jq(meta)}, 'proposed') ON CONFLICT (id) DO NOTHING;`)
    for (const p of pairs) {
      w('INSERT INTO lpm_object_tags (project_id, data_object_id, schema_element_id, role)')
      w(`VALUES (${q(project.id)}, ${q(p.stage_id)}, ${q(uid('element', key, id))}, ${q(`${p.relation}-${p.strength}`)}) ON CONFLICT (data_object_id, schema_element_id) DO NOTHING;`)
      nTags++
    }
  }
  // Concept alignments
  for (const ca of al.conceptAlignments) {
    const el = conceptEl.get(ca.concept)
    if (!el) { warnings.push(`${key}: concept ${ca.concept} not found`); continue }
    const entry = ca.items.map((id) => ({ competencybase_id: id, human_coding_scheme: R[id].code, relation: ca.relation, why: ca.why }))
    w(`UPDATE lpm_schema_elements SET metadata = metadata || jsonb_build_object('ai4k12_alignment', ${jq(entry)}) WHERE id = ${q(el.id)};`)
  }
  // Introduction paragraph
  const sa = al.stageAlignments
  const withItems = sa.filter((s) => s.items.length).length
  const cnt = { strong: 0, partial: 0, weak: 0 }
  for (const s of sa) for (const it of s.items) cnt[it.strength]++
  const nGap = [...gaps.keys()].filter((g) => !aligned.has(g)).length
  const para = `Alignment with AI4K12. This space is aligned with the AI4K12 progression charts (Five Big Ideas in Artificial Intelligence, held in CompetencyBase) with ${sp.focus}. ${withItems} of ${sa.length} stages align with at least one AI4K12 item of the same grade band (${cnt.strong} strong, ${cnt.partial} partial and ${cnt.weak} weak matches), and ${nGap} AI4K12 items inside the focus have no stage and are listed as gaps in the taxonomy. A match was made only where a teacher could defend it. The alignments are proposed. AI drafted them and no subject expert has reviewed them.`
  w(`UPDATE projects SET introduction = introduction || ${q('\n\n' + para)} WHERE id = ${q(project.id)} AND introduction NOT LIKE ${q('%Alignment with AI4K12. This space%')};`)
  w('')
  stats[key] = { elements: order.length, aligned: aligned.size, gaps: nGap, tags: nTags, stagesWithItems: withItems, ...cnt }
}
process.stdout.write(lines.join('\n') + '\n')
process.stderr.write(JSON.stringify(stats) + '\n')
for (const x of warnings) process.stderr.write('WARNING: ' + x + '\n')
