#!/usr/bin/env node
// Generates the migration that creates the Social-Core and Computational-Core synthetic LPM spaces.
//
//   node scripts/generate_core_spaces_content_migration.mjs > supabase/migrations/180_social_computational_core_synthetic_spaces.sql
//
// Content is authored in scripts/data/core-spaces-content.json from the design note
// lab_manager/docs/design-notes/social-core-and-computational-core-synthetic-lpm-preparation-2026-10-25.md.
// For each space this writes: the project (private, status draft) with its trunk branch and members, 15 concepts, 3 strands
// and 12 stages with their concept tags, the strand/stage connections, one thread per strand with stations, literature
// references read from the LiteratureBase clone, and a source declaration. Everything is AI-drafted and unreviewed.
// Ids are uuid5-derived, so re-running gives identical SQL, and every insert is idempotent.

import { readFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const C = JSON.parse(readFileSync(path.join(root, 'scripts/data/core-spaces-content.json'), 'utf8'))
const LB = process.env.LITERATUREBASE_DIR || 'D:/dev/openevo-ccs-lab/literaturebase'
const NS = uuid5('https://openevo-ccs.github.io/openlpm/core-spaces-2026-10-25', uuid5.URL)
const uid = (...p) => uuid5(p.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const dq = (s) => '$J$' + String(s) + '$J$'
const jb = (o) => q(JSON.stringify(o)) + '::jsonb'
const arr = (xs) => 'ARRAY[' + xs.map(q).join(', ') + ']::text[]'

const lines = []
const w = (s = '') => lines.push(s)
const warnings = []

const BANDS = ['K-2', '3-5', '6-8', '9-12']
const TYPE_MAP = { 'journal-article': 'article', article: 'article', 'book-chapter': 'chapter', chapter: 'chapter', book: 'book', report: 'report', thesis: 'thesis' }

w(`-- Social-Core and Computational-Core synthetic LPM spaces.
-- Generated by scripts/generate_core_spaces_content_migration.mjs from scripts/data/core-spaces-content.json; do not hand-edit.
--
-- Two new synthetic comparison spaces for the four-space comparison (Bio-Core, Social-Core, Computational-Core,
-- Interdisciplinary). Each follows the preparation note: 15 concepts, 3 strands, 12 stages across K-2, 3-5, 6-8 and 9-12.
-- Prerequisite links were authored from each domain's own logic and do not copy Bio-Core's template, so that a comparison
-- of order structure does not measure the template.
--
-- Everything here is AI-drafted on 2026-10-25 and no subject-matter expert has reviewed it. Social-Core carries the equity
-- risk named in the note and was built on Dustin's instruction before any review. Both projects are created private
-- (members only) with maturity 'draft'. Making them visible to everyone is one UPDATE of projects.is_private.
--
-- Concept ids in stage content are proposed ids (OE-CONCEPT-<space>-<concept>). None is registered in ConceptBase.
-- Rollback: DELETE FROM projects WHERE slug IN ('social-core-lpm-synth', 'computational-core-lpm-synth') removes
-- everything below by cascade.

SET search_path = public, extensions;

DO $MIGRATION$
DECLARE
  v_user UUID;
  v_qa UUID;
  v_project UUID;
  v_branch UUID;
BEGIN
  SELECT id INTO v_user FROM users WHERE email = 'dustin.eirdosh@eva.mpg.de';
  SELECT id INTO v_qa FROM users WHERE email = 'dustin+openlpmtest2@globalesd.org';
`)

for (const sp of C.spaces) {
  const pid = uid('project', sp.slug)
  const spaceKey = sp.key
  const cid = (slug) => uid('concept', spaceKey, slug)
  const conceptbaseId = (slug) => `OE-CONCEPT-${spaceKey}-core-${slug}`
  const strandId = (code) => uid('strand', spaceKey, code)
  const stageId = (code, band) => uid('stage', spaceKey, code, band)
  const sourceStrandId = (s) => `OE-STRAND-${spaceKey}-core-${s.slug}`
  const sourceStageId = (s, band) => `${sourceStrandId(s)}-${band}`
  const strandByCode = Object.fromEntries(sp.strands.map((s) => [s.code, s]))
  const stageByRef = {}
  for (const s of sp.strands) for (const st of s.stages) stageByRef[`${s.code}:${st.band}`] = { s, st }

  w(`  -- ==========================================================================`)
  w(`  -- ${sp.slug}`)
  w(`  -- ==========================================================================`)
  w(`  INSERT INTO projects (id, slug, name, description, status, epistemic_status, epistemic_status_note, hosting_mode, is_private, maturity, focus_type, region_tags, theme_tags, working_languages, color, introduction)`)
  w(`  VALUES (${q(pid)}, ${q(sp.slug)}, ${dq(sp.name)}, ${dq(sp.description)}, 'active', 'designed-thought-experiment', ${dq(sp.epistemicNote)}, 'hosted', TRUE, 'draft', 'general', '{}'::text[], '{}'::text[], ARRAY['en']::text[], ${q(sp.color)}, ${dq(sp.introduction)})`)
  w(`  ON CONFLICT (slug) DO NOTHING;`)
  w(`  SELECT id INTO v_project FROM projects WHERE slug = ${q(sp.slug)};`)
  w(`  INSERT INTO branches (project_id, slug, label, is_trunk, status) VALUES (v_project, 'main', 'Trunk', TRUE, 'active') ON CONFLICT (project_id, slug) DO NOTHING;`)
  w(`  SELECT id INTO v_branch FROM branches WHERE project_id = v_project AND is_trunk = TRUE;`)
  w(`  IF v_user IS NOT NULL THEN`)
  w(`    INSERT INTO project_members (project_id, user_id, role) VALUES (v_project, v_user, 'owner') ON CONFLICT (project_id, user_id) DO UPDATE SET role = 'owner';`)
  w(`    UPDATE projects SET created_by = v_user WHERE id = v_project AND created_by IS NULL;`)
  w(`  END IF;`)
  w(`  IF v_qa IS NOT NULL THEN`)
  w(`    INSERT INTO project_members (project_id, user_id, role) VALUES (v_project, v_qa, 'viewer') ON CONFLICT (project_id, user_id) DO NOTHING;`)
  w(`  END IF;`)
  w()
  w(`  INSERT INTO project_source_declarations (project_id, source_name, format, license_or_rights_note, url)`)
  w(`  SELECT v_project, ${q('Design note: social-core-and-computational-core-synthetic-lpm-preparation-2026-10-25 (lab_manager)')}, ${q('Markdown design note, content authored in a JSON file and generated into this migration')}, ${q('AI-drafted 2026-10-25. No expert review.')}, NULL`)
  w(`  WHERE NOT EXISTS (SELECT 1 FROM project_source_declarations WHERE project_id = v_project AND source_name = ${q('Design note: social-core-and-computational-core-synthetic-lpm-preparation-2026-10-25 (lab_manager)')});`)
  w()

  // Concepts
  w(`  -- Concepts (${sp.concepts.length}, ${sp.vocabulary})`)
  w(`  INSERT INTO lpm_schema_elements (id, project_id, element_type, label, definition, parent_id, metadata, status)`)
  w(`  VALUES`)
  w(sp.concepts.map((c) => {
    const meta = { definition: c.definition, vocabulary: sp.vocabulary, conceptbase_id: conceptbaseId(c.slug), conceptbase_registered: false, origin: c.origin === 'interdisciplinary' ? 'Interdisciplinary vocabulary, restricted to its sense in this domain' : 'New in this space', draft_note: 'AI-drafted 2026-10-25. No expert has reviewed this definition.' }
    return `  (${q(cid(c.slug))}, v_project, 'concept', ${q(c.label)}, ${dq(c.definition)}, NULL, ${jb(meta)}, 'proposed')`
  }).join(',\n'))
  w(`  ON CONFLICT (id) DO NOTHING;`)
  w()

  // Literature rows, read from the LiteratureBase clone.
  const litByStrand = {}
  const litRows = []
  for (const l of sp.literature) {
    const slug = l.id.replace(/^OE-LITERATURE-/, '')
    // File names do not always match ids (for example lit-mesoudi-2011.yaml holds OE-LITERATURE-mesoudi-2011).
    const f = [`${slug}.yaml`, `lit-${slug}.yaml`].map((n) => path.join(LB, 'records', n)).find((x) => existsSync(x))
    if (!f) { warnings.push(`${sp.slug}: ${l.id} not found in ${LB}`); continue }
    const rec = yaml.load(readFileSync(f, 'utf8'))
    const c = rec.citation ?? {}
    for (const code of l.strands) (litByStrand[code] ??= []).push(l.id)
    litRows.push({ id: l.id, title: c.title, authors: c.authors ?? [], year: c.year ?? null, doi: c.doi ?? null, venue: c.venue ?? c.publisher ?? null, type: TYPE_MAP[rec.type] ?? null, role: l.role, strands: l.strands })
  }

  // Strands and stages
  w(`  -- Strands and stages`)
  w(`  INSERT INTO lpm_data_objects (id, project_id, branch_id, object_type, title, description, grade_band, subject_area, content, status)`)
  w(`  VALUES`)
  const objRows = []
  for (const s of sp.strands) {
    const content = {
      source_id: sourceStrandId(s),
      description: s.description,
      associatedDomains: [sp.domain],
      relations: Object.fromEntries(Object.entries(s.relations).map(([k, v]) => [k, v.map((code) => sourceStrandId(strandByCode[code]))])),
      epistemicStatus: 'designed-thought-experiment',
      anchors: s.anchors,
      draft_note: 'AI-drafted 2026-10-25 from the preparation note. No expert has reviewed it.',
      _source: { repo: `${spaceKey}-core-draft-2026-10-25`, path: `strands/strand-${s.code.toLowerCase()}-${s.slug}.yaml` },
    }
    objRows.push(`  (${q(strandId(s.code))}, v_project, v_branch, 'strand', ${dq(s.title)}, ${dq(s.description.slice(0, 500))}, 'K-12', ${q(sp.domain)}, ${jb(content)}, 'accepted')`)
    for (const st of s.stages) {
      const outgoing = sp.stageEdges.filter((e) => e.from === `${s.code}:${st.band}`)
      const sc = {
        source_id: sourceStageId(s, st.band),
        performanceIndicators: st.pis,
        concepts: st.concepts.map(([slug, emphasis]) => ({ id: conceptbaseId(slug), emphasis })),
        required: true,
        ...(outgoing.length ? { relations: { prerequisiteOf: outgoing.map((e) => { const t = stageByRef[e.to]; return sourceStageId(t.s, t.st.band) }) } } : {}),
        literature_ids: litByStrand[s.code] ?? [],
        draft_note: 'AI-drafted 2026-10-25 from the preparation note. No expert has reviewed it.',
        _source: { repo: `${spaceKey}-core-draft-2026-10-25`, path: `strands/strand-${s.code.toLowerCase()}-${s.slug}.yaml` },
      }
      const labels = st.concepts.map(([slug]) => sp.concepts.find((c) => c.slug === slug).label)
      objRows.push(`  (${q(stageId(s.code, st.band))}, v_project, v_branch, 'substrand', ${dq(st.title)}, ${dq('Key concepts: ' + labels.join(', '))}, ${q(st.band)}, ${q(sp.domain)}, ${jb(sc)}, 'accepted')`)
    }
  }
  w(objRows.join(',\n'))
  w(`  ON CONFLICT (id) DO NOTHING;`)
  w()

  // Connections
  w(`  -- Connections: isChildOf, strand relations, and stage prerequisites authored for this domain`)
  w(`  INSERT INTO lpm_connections (project_id, from_object_id, to_object_id, relation_type, kind, rationale, status)`)
  w(`  VALUES`)
  const connRows = []
  for (const s of sp.strands) {
    for (const st of s.stages) connRows.push(`  (v_project, ${q(stageId(s.code, st.band))}, ${q(strandId(s.code))}, 'isChildOf', 'asserted', NULL, 'accepted')`)
    for (const [rel, targets] of Object.entries(s.relations)) for (const t of targets) connRows.push(`  (v_project, ${q(strandId(s.code))}, ${q(strandId(t))}, ${q(rel)}, 'asserted', NULL, 'accepted')`)
  }
  for (const e of sp.stageEdges) {
    const a = stageByRef[e.from]
    const b = stageByRef[e.to]
    connRows.push(`  (v_project, ${q(stageId(a.s.code, a.st.band))}, ${q(stageId(b.s.code, b.st.band))}, 'prerequisiteOf', 'asserted', ${dq(e.rationale)}, 'accepted')`)
  }
  w(connRows.join(',\n'))
  w(`  ON CONFLICT (from_object_id, to_object_id, relation_type) DO NOTHING;`)
  w()

  // Tags
  w(`  -- Object tags: stage to concept, role = emphasis`)
  w(`  INSERT INTO lpm_object_tags (project_id, data_object_id, schema_element_id, role)`)
  w(`  VALUES`)
  const tagRows = []
  for (const s of sp.strands) for (const st of s.stages) for (const [slug, emphasis] of st.concepts) tagRows.push(`  (v_project, ${q(stageId(s.code, st.band))}, ${q(cid(slug))}, ${q(emphasis)})`)
  w(tagRows.join(',\n'))
  w(`  ON CONFLICT (data_object_id, schema_element_id) DO NOTHING;`)
  w()

  // Threads and stations
  w(`  -- One thread per strand, its stages as ordered stations`)
  w(`  INSERT INTO lpm_threads (id, project_id, branch_id, slug, title, thread_type, connecting_idea, narrative, status)`)
  w(`  VALUES`)
  w(sp.strands.map((s) => `  (${q(uid('thread', spaceKey, s.code))}, v_project, v_branch, ${q(s.slug)}, ${dq(s.title)}, 'vertical', ${dq(s.connectingIdea)}, ${dq(s.description)}, 'accepted')`).join(',\n'))
  w(`  ON CONFLICT (project_id, slug) DO NOTHING;`)
  w()
  w(`  INSERT INTO lpm_thread_stations (id, thread_id, data_object_id, sequence, role_note, relation_to_next)`)
  w(`  VALUES`)
  const stRows = []
  for (const s of sp.strands) {
    s.stages.forEach((st, i) => {
      const labels = st.concepts.map(([slug]) => sp.concepts.find((c) => c.slug === slug).label)
      const next = s.stages[i + 1]
      stRows.push(`  (${q(uid('station', spaceKey, s.code, st.band))}, ${q(uid('thread', spaceKey, s.code))}, ${q(stageId(s.code, st.band))}, ${i + 1}, ${dq(`${st.band}, ${st.title}. Key concepts: ${labels.join(', ')}.`)}, ${next ? dq(`Leads into ${next.title} (${next.band}).`) : 'NULL'})`)
    })
  }
  w(stRows.join(',\n'))
  w(`  ON CONFLICT (thread_id, sequence) DO NOTHING;`)
  w()
  const parentRows = []
  for (const s of sp.strands) for (const [rel, targets] of Object.entries(s.relations)) for (const t of targets) parentRows.push(`  (${q(uid('strand-parent', spaceKey, t, s.code))}, ${q(uid('thread', spaceKey, t))}, ${q(uid('thread', spaceKey, s.code))})`)
  if (parentRows.length) {
    w(`  -- foundationalTo / prerequisiteOf read as: the target strand nests under this one`)
    w(`  INSERT INTO strand_parents (id, strand_id, parent_strand_id)`)
    w(`  VALUES`)
    w(parentRows.join(',\n'))
    w(`  ON CONFLICT (strand_id, parent_strand_id) DO NOTHING;`)
    w()
  }

  // Literature
  w(`  -- Literature: anchors are native sources of the domain, contrast cases are bridge sources used only to show what the other spaces add`)
  for (const r of litRows) {
    const note = `${r.role === 'anchor' ? 'Proposed anchor' : 'Contrast case only, used to show what the other spaces add'}, for ${sp.name.replace(' LPM (Synthetic)', '')} strand${r.strands.length > 1 ? 's' : ''} ${r.strands.join(', ')} (2026-10-25). Match made from the design note and the record's title and domains; not read in full. Draft until a subject-matter expert reviews it.`
    w(`  INSERT INTO literature_references (project_id, literaturebase_id, title, authors, year, doi, venue, type, status, notes, tags)`)
    w(`  SELECT v_project, ${q(r.id)}, ${dq(r.title ?? r.id)}, ${jb(r.authors)}, ${r.year ?? 'NULL'}, ${r.doi ? q(r.doi) : 'NULL'}, ${r.venue ? q(r.venue) : 'NULL'}, ${r.type ? q(r.type) : 'NULL'}, 'draft', ${dq(note)}, ${arr(['proposed-link', r.role])}`)
    w(`  WHERE NOT EXISTS (SELECT 1 FROM literature_references WHERE project_id = v_project AND literaturebase_id = ${q(r.id)});`)
  }
  w()
}

w(`END $MIGRATION$;`)
process.stdout.write(lines.join('\n') + '\n')
for (const x of warnings) process.stderr.write('WARNING: ' + x + '\n')
