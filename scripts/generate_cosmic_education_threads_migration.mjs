#!/usr/bin/env node
/**
 * Generates the Strands-tab storylines of the Cosmic Education LPM spaces: one thread per Great Lesson strand,
 * walking through that strand's stages GB-0 to GB-3 (Montessori's own scope plus the informal early stage).
 * Reuses the ids of generate_cosmic_education_lpm_seed.mjs (same uuid5 namespace), so it points at rows that exist.
 * Run: node scripts/generate_cosmic_education_threads_migration.mjs > supabase/migrations/236_cosmic_education_lpm_strand_threads.sql
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import yaml from "js-yaml";

const SRC = "D:/dev/openevo-ccs-lab/cosmic-education-k12";
function uuidv5(name, ns) {
  const h0 = crypto.createHash("sha1").update(Buffer.concat([Buffer.from(ns.replace(/-/g, ""), "hex"), Buffer.from(name, "utf8")])).digest();
  h0[6] = (h0[6] & 0x0f) | 0x50;
  h0[8] = (h0[8] & 0x3f) | 0x80;
  const h = h0.subarray(0, 16).toString("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
}
const NS = uuidv5("https://openevo.net/openlpm/cosmic-education-lpm-seed", "00000000-0000-0000-0000-000000000000");
const uid = (k) => uuidv5(k, NS);
const J = (s) => {
  s = String(s ?? "");
  if (s.includes("$J$")) throw new Error("$J$");
  return `$J$${s}$J$`;
};
const clean = (s) => String(s).replace(/\s+/g, " ").trim();

const HUB = { 1: "great-story", 2: "cosmic-task", 3: "fundamental-human-needs", 4: "sign-and-symbol", 5: "quantity-and-symbol" };
const SLUG = { 1: "story-of-the-universe", 2: "story-of-life", 3: "story-of-humans", 4: "story-of-language", 5: "story-of-numbers" };
const GBS = yaml.load(fs.readFileSync(path.join(SRC, "lpm/grade-bands.yaml"), "utf8")).gradeBands;

const out = [];
const w = (s = "") => out.push(s);
w(`-- 236: The five Great Lesson strands as storylines in the Strands tab of both Cosmic Education language spaces (Dustin, 2026-11-07).`);
w(`-- The Strands tab lists named sequences through stages, so each strand becomes one storyline across its stages GB-0 to GB-3 (GB-4 to GB-6 only hand off`);
w(`-- to other models and stay out). 5 storylines per language space, 4 stations each. Status 'proposed'. Wording comes from the draft's own strand text and`);
w(`-- essential questions (the German space uses the draft's German). Nobody has reviewed any of it.`);
w(`-- Generated by scripts/generate_cosmic_education_threads_migration.mjs. Running this twice changes nothing.`);
w(`-- Rollback: DELETE FROM lpm_threads WHERE slug LIKE 'cosmic-%' AND project_id IN (SELECT id FROM projects WHERE slug IN ('cosmic-education-lpm-en','cosmic-education-lpm-de'));`);
w(`SET search_path = public, extensions;`);
w(`DO $MIGRATION$`);
w(`DECLARE v_proj UUID; v_branch UUID;`);
w(`BEGIN`);
for (const L of ["en", "de"]) {
  w(`  SELECT p.id, b.id INTO v_proj, v_branch FROM projects p JOIN branches b ON b.project_id = p.id AND b.is_trunk WHERE p.slug = 'cosmic-education-lpm-${L}';`);
  w(`  IF v_proj IS NULL THEN RAISE EXCEPTION 'cosmic-education-lpm-${L} missing'; END IF;`);
  for (let n = 1; n <= 5; n++) {
    const f = fs.readdirSync(path.join(SRC, "lpm/strands")).find((x) => x.startsWith(`strand-${n}-`));
    const d = yaml.load(fs.readFileSync(path.join(SRC, "lpm/strands", f), "utf8"));
    const eq = d.extensions["cosmic-k12:essentialQuestion"];
    const tid = uid(`${L}:thread:${d.id}`);
    const hubId = uid(`${L}:concept:OE-CONCEPT-cosmic-k12-${HUB[n]}`);
    const review =
      L === "en"
        ? "Built from the cosmic-education-k12 draft's strand text and essential questions. No expert has reviewed it. Montessori's own scope is ages 6 to 12; the draft calls the progression a designed thought experiment that has not been tested against children's reasoning."
        : "Aus Strangtext und Leitfragen des Entwurfs cosmic-education-k12 zusammengestellt. Keine Fachperson hat es geprüft. Montessoris eigener Geltungsbereich sind die Altersstufen 6 bis 12; der Entwurf nennt die Progression ein Gedankenexperiment, das noch nicht am Denken von Kindern geprüft wurde.";
    w(`  INSERT INTO lpm_threads (id, project_id, branch_id, slug, title, thread_type, explained_by_element_id, connecting_idea, narrative, teaching_prompt, evidence_note, gaps, status)`);
    w(`  VALUES ('${tid}', v_proj, v_branch, 'cosmic-${SLUG[n]}', ${J(d.labels[L])}, 'vertical', '${hubId}', ${J(clean(eq.broad[L]))}, ${J(clean(d.description[L]))}, ${J(clean(eq.worked[L]))}, ${J(review)}, '[]'::jsonb, 'proposed')`);
    w(`  ON CONFLICT (project_id, slug) DO NOTHING;`);
    let seq = 0;
    for (const sub of d.subStrands) {
      const gb = Number(sub.id.match(/-gb(\d)$/)[1]);
      if (gb > 3) continue;
      seq++;
      const info = GBS.find((g) => g.id === `GB-${gb}`);
      const note = `${info.label[L]}, ${L === "en" ? "ages" : "Alter"} ${info.approxAge}: ${sub.labels[L] || sub.labels.en}`;
      w(`  INSERT INTO lpm_thread_stations (id, thread_id, data_object_id, sequence, role_note, via_element_id, relation_to_next)`);
      w(`  VALUES ('${uid(`${L}:station:${sub.id}`)}', '${tid}', '${uid(`${L}:substrand:${sub.id}`)}', ${seq}, ${J(note)}, '${hubId}', ${gb < 3 ? J(L === "en" ? "deepens" : "vertieft") : "NULL"})`);
      w(`  ON CONFLICT (thread_id, sequence) DO NOTHING;`);
    }
  }
}
w(`END $MIGRATION$;`);
process.stdout.write(out.join("\n") + "\n");
