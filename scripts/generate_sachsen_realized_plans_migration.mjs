#!/usr/bin/env node
// Generates the migration that adds, for each of the four synthetic spaces, a plan that shows how the real Sachsen curriculum
// realises the space: each stage gets the guidance hours of the real topics that cover it, in the grades where those topics sit.
//
//   node scripts/generate_sachsen_realized_plans_migration.mjs scripts/data/sachsen-stage-topic-relations.json > supabase/migrations/184_sachsen_realized_plans.sql
//
// Input: the stage-to-topic relations computed by the pilot in deutsche_lp (land/sachsen/lp/data/pilot-concept-tagging/stage-topic-mapping).
// A relation joins a stage to a topic through shared concepts, tagged by AI and not audited by a person. Only pairs classed as
// covers or partly covers are used. The hours of a topic are split over the stages it relates to in proportion to the concepts
// they share and scaled by the share of the topic's tagged concepts that the space's vocabulary holds.
// The plans sit on the Sachsen timetable of migration 183 and put each placement on the axis of the topic's subject.
// Ids are uuid5-derived. Content of Bio-Core and Interdisciplinary project ids is read from the live database.

import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const rel = JSON.parse(readFileSync(path.resolve(process.argv[2]), 'utf8'))
const topics = JSON.parse(readFileSync(path.resolve(process.argv[3]), 'utf8'))
const topicById = new Map(topics.map((t) => [t.topicId, t]))
const env = readFileSync(path.join(root, '.env.local'), 'utf8')
const URL_ = env.match(/VITE_SUPABASE_URL=(.*)/)[1].trim().replace(/^"|"$/g, '')
const KEY = readFileSync(path.join(root, '.supabase-secrets', 'service-role-key.txt'), 'utf8').trim()
async function rest(p) {
  const r = await fetch(`${URL_}/rest/v1/${p}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
  if (!r.ok) throw new Error(`${p}: ${r.status}`)
  return r.json()
}
const NS = uuid5('https://openevo-ccs.github.io/openlpm/sachsen-timetable-2026-10-25', uuid5.URL)
const uid = (...p) => uuid5(p.join('/'), NS)
const CORE_NS = uuid5('https://openevo-ccs.github.io/openlpm/core-spaces-2026-10-25', uuid5.URL)
const coreUid = (...p) => uuid5(p.join('/'), CORE_NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const sqlOrNull = (v) => (v === null || v === undefined ? 'NULL' : q(v))

const SUBJECT_AXIS = { biologie: 'biology', informatik: 'computer-science', 'technik-computer': 'computer-science', ethik: 'social-studies', 'gemeinschaftskunde-rechtserziehung-wirtschaft': 'social-studies', geschichte: 'social-studies', geographie: 'social-studies', sachunterricht: 'sachunterricht' }
const SPACES = [
  { key: 'bio', slug: 'bio-core-lpm-synth', home: 'biology', label: 'Bio-Core' },
  { key: 'soc', slug: 'social-core-lpm-synth', home: 'social-studies', label: 'Social-Core' },
  { key: 'comp', slug: 'computational-core-lpm-synth', home: 'computer-science', label: 'Computational-Core' },
  { key: 'int', slug: 'interdisciplinary-lpm-synth', home: 'biology', label: 'Interdisciplinary' },
]
const lines = []
const w = (s = '') => lines.push(s)
w(`-- How the real Sachsen curriculum realises each synthetic space, as a plan on the Sachsen timetable of migration 183.
-- Generated by scripts/generate_sachsen_realized_plans_migration.mjs; do not hand-edit.
--
-- Each stage gets the guidance hours (Zeitrichtwerte) of the real topics that cover it, in the grades where those topics sit and
-- on the timetable of the topic's subject. The relation between a stage and a topic comes from concepts they share, tagged by AI
-- and not audited by a person (deutsche_lp, land/sachsen/lp/data/pilot-concept-tagging). Only pairs that cover or partly cover a
-- stage are used. The plan lets the Time page set the real curriculum beside the starter plans of the same space on the same hours.
-- Everything is AI-drafted, status 'proposed', confidence low.

SET search_path = public, extensions;
`)
const stats = []
for (const sp of SPACES) {
  const pid = sp.key === 'bio' || sp.key === 'int' ? (await rest(`projects?select=id&slug=eq.${sp.slug}`))[0].id : coreUid('project', sp.slug)
  const axisId = (subject) => uid('axis', pid, subject)
  const planId = uid('plan', pid, 'sachsen-realized')
  const rows = rel[sp.key]
  const params = { realized: 'sachsen-tags-v1' }
  const name = 'Sachsen Lehrplan as realised (from concept tags)'
  const summary = `How the real Sachsen curriculum realises ${sp.label}: each stage gets the guidance hours of the real topics that cover it, in the grades where those topics sit and on the timetable of the topic's subject. The match rests on concepts tagged by AI and not audited by a person. Grades 11 and 12 are not in the data. It describes the curriculum and makes no recommendation.`
  w(`-- ${sp.slug}: ${rows.length} placements`)
  w('INSERT INTO lpm_time_plans (id, project_id, axis_id, name, summary, kind, parameters, status)')
  w(`VALUES (${q(planId)}, ${q(pid)}, ${q(axisId(sp.home))}, ${q(name)}, ${q(summary)}, 'scheduled', ${jq(params)}, 'proposed') ON CONFLICT (id) DO NOTHING;`)
  let total = 0
  rows.sort((a, b) => a.stageId.localeCompare(b.stageId) || a.topicId.localeCompare(b.topicId)).forEach((r, i) => {
    const t = topicById.get(r.topicId)
    const years = [...new Set(r.grades.map((g) => g + 1))].sort((a, b) => a - b)
    const minutes = Math.round(r.hoursUstd * 45)
    total += minutes
    const note = `Realised by the Sachsen topic "${t.title}" (${t.subject}, grade ${r.grades.join('/')}), ${r.class === 'covers' ? 'covers the stage' : 'partly covers the stage'}.`
    const selector = { where: { year: { in: years, absolute: true } } }
    const amount = { kind: 'total', low: `PT${minutes}M` }
    const id = uid('placement', planId, String(i))
    w('INSERT INTO lpm_time_placements (id, plan_id, target_type, target_id, role, resource, selector, amount, note, sort_order, axis_id)')
    w(`VALUES (${q(id)}, ${q(planId)}, 'topic', ${q(r.stageId)}, 'dedicated', 'instructional_time', ${jq(selector)}, ${jq(amount)}, ${q(note)}, ${i}, ${q(axisId(SUBJECT_AXIS[r.subject]))}) ON CONFLICT (id) DO NOTHING;`)
  })
  const assumptions = [
    ['The hours of a stage are the Zeitrichtwerte of the Sachsen topics that cover it, split over the stages a topic relates to in proportion to the concepts they share and scaled by the share of the topic\'s tagged concepts that this space holds.', 'derived', 'low', 'deutsche_lp land/sachsen/lp/data/pilot-concept-tagging, stage-topic mapping of 2026-10-25.', 'The rule is arbitrary. The weights (primary 1, reinforcing 0.4) and the thresholds for covers and partly covers were also run at reinforcing 0.2 and 0.6, and the number of stages with a real topic moved by one or two.'],
    ['The relation between a stage and a topic comes from concept tags made by AI on both sides and not audited by a person.', 'derived', 'low', 'Two independent AI passes tagged the topics (73 percent of distinct tags shared). The stage tags come from the space authors.', 'A stage with no real topic can be a real gap or a limit of the shared vocabulary. A sample audit by the team decides which.'],
    ['Grades 1 to 4 are Sachunterricht topics, grades 5 to 10 are Gymnasium topics of Biologie, Informatik, Technik/Computer, Gemeinschaftskunde, Geschichte, Geographie and Ethik. Grades 11 and 12, the Oberschule and other subjects are not in the data.', 'derived', 'high', 'deutsche_lp land/sachsen/lp/data.', 'The stages of the 9-12 band can only find grade 9 and 10 topics, so they look earlier than their band.'],
    ['A guidance hour is one Unterrichtsstunde of 45 minutes, and a Zeitrichtwert is a guidance value for a topic and differs from the time a class actually spends on it.', 'literature', 'high', 'Sachsen Lehrpläne and VwV Stundentafeln.', 'The Lehrpläne plan with 25 of about 39 weeks. The hours here fall inside that plan.'],
  ]
  assumptions.forEach(([statement, type, conf, src, why], i) => {
    const aid = uid('assumption', pid, `realized-${i}`)
    w('INSERT INTO lpm_time_assumptions (id, project_id, plan_id, axis_id, projection_id, statement, assumption_type, confidence, source, rationale, value)')
    w(`VALUES (${q(aid)}, ${q(pid)}, ${q(planId)}, NULL, NULL, ${q(statement)}, ${q(type)}, ${q(conf)}, ${q(src)}, ${q(why)}, NULL) ON CONFLICT (id) DO NOTHING;`)
  })
  w()
  stats.push(`${sp.slug}: ${rows.length} placements, ${(total / 60).toFixed(0)} clock hours`)
}
process.stdout.write(lines.join('\n') + '\n')
for (const s of stats) process.stderr.write(s + '\n')
