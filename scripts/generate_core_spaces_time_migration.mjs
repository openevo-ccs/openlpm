#!/usr/bin/env node
// Generates the time layer seeds for the Social-Core and Computational-Core synthetic spaces (migration 180 creates the spaces).
//
//   node scripts/generate_core_spaces_time_migration.mjs > supabase/migrations/181_core_spaces_time_layer.sql
//
// Per space: three subject timetables (biology, social studies, computer science) with the same placeholder hours as the
// Bio-Core and Interdisciplinary spaces, and five plans on the timetable of the space's home subject: a capstone, a threaded
// and a spiral starter plan, a sequenced plan in dependency order and its reverse as a negative control. The order of the
// sequenced plans comes from each space's own authored prerequisite links. Everything is AI-drafted, status 'proposed', and
// every hour figure is a placeholder with no source. Ids are uuid5-derived from the same namespace as migration 180.

import { build } from 'esbuild'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const dir = mkdtempSync(path.join(tmpdir(), 'core-time-'))
const out = path.join(dir, 'time.mjs')
await build({ entryPoints: [path.join(root, 'src/lib/time/index.ts')], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error' })
const T = await import(pathToFileURL(out).href)
rmSync(dir, { recursive: true, force: true })

const C = JSON.parse(readFileSync(path.join(root, 'scripts/data/core-spaces-content.json'), 'utf8'))
const NS = uuid5('https://openevo-ccs.github.io/openlpm/core-spaces-2026-10-25', uuid5.URL)
const uid = (...p) => uuid5(p.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const sqlOrNull = (v) => (v === null || v === undefined ? 'NULL' : q(v))
const SHARE = { low: 0.1, high: 0.3 }
const BANDS = T.BAND_NAMES

// Placeholder hours per subject. Biology follows Dustin's estimate of 2026-10-25 (revised the same day). The other two
// have no source and are chosen to claim as little as possible.
const SUBJECTS = [
  { key: 'biology', label: 'Biology', tiers: T.DEFAULT_TIER_HOURS, notes: T.TIER_NOTES, statement: 'Biology gets 8-21 hours a year in the lower grades, 20-38 in the middle grades and 50-70 in the upper grades.', why: 'Dustin Eirdosh gave 50-70 hours for the upper grades on 2026-10-25 (his first figure of 100-150 was judged too high). The lower and middle figures scale his earlier ranges by the same ratio. No published source yet.', type: 'estimate' },
  { key: 'social-studies', label: 'Social studies', tiers: T.DEFAULT_TIER_HOURS, notes: { lower: 'Placeholder, no source: the same hours as biology.', middle: 'Placeholder, no source: the same hours as biology.', upper: 'Placeholder, no source: the same hours as biology.' }, statement: 'Social studies gets the same hours a year as biology: 8-21 in the lower grades, 20-38 in the middle grades and 50-70 in the upper grades.', why: 'No figure for this subject exists yet. Matching biology adds no outside claim. Replace it with the local timetable.', type: 'placeholder' },
  { key: 'computer-science', label: 'Computer science', tiers: { lower: { low: 0, high: 0 }, middle: { low: 10, high: 19 }, upper: { low: 25, high: 35 } }, notes: { lower: 'Placeholder, no source: no separate computer science hours in K-4.', middle: 'Placeholder, no source: half of the biology hours.', upper: 'Placeholder, no source: half of the biology hours.' }, statement: 'Computer science gets no hours in the lower grades (K-4), 10-19 hours a year in the middle grades and 25-35 in the upper grades.', why: 'No figure for this subject exists yet. Half of the biology hours in grades 5-12 and none before is a deliberately low placeholder. Replace it with the local timetable.', type: 'placeholder' },
]

const lines = []
const w = (s = '') => lines.push(s)

w(`-- Time layer seeds for the Social-Core and Computational-Core synthetic spaces (created by migration 180).
-- Generated by scripts/generate_core_spaces_time_migration.mjs; do not hand-edit.
--
-- Each space gets three subject timetables with placeholder hours and five plans on its home subject's timetable. The order
-- checks of the sequenced plans use the prerequisite links authored for the space. A space that lives in one subject is the
-- point of a domain core, so no plan here draws on another subject. The Time page lets a user try a split.
-- Everything is AI-drafted, status 'proposed', and every hour figure is a placeholder with no source.

SET search_path = public, extensions;
`)

for (const sp of C.spaces) {
  const pid = uid('project', sp.slug)
  const spaceKey = sp.key
  const strandByCode = Object.fromEntries(sp.strands.map((s) => [s.code, s]))
  const stageId = (code, band) => uid('stage', spaceKey, code, band)
  const conceptbaseId = (slug) => `OE-CONCEPT-${spaceKey}-core-${slug}`
  const stages = []
  for (const s of sp.strands) for (const st of s.stages) {
    stages.push({ id: stageId(s.code, st.band), title: st.title, band: st.band, strand: `strands/strand-${s.code.toLowerCase()}-${s.slug}.yaml`, concepts: st.concepts.map(([slug, emphasis]) => ({ id: conceptbaseId(slug), emphasis })), outcomes: st.pis.length, required: true })
  }
  stages.sort((a, b) => a.id.localeCompare(b.id))
  const sources = { stageStrand: {}, strandEdges: [], stageEdges: [], threads: [] }
  for (const s of sp.strands) {
    for (const st of s.stages) sources.stageStrand[stageId(s.code, st.band)] = uid('strand', spaceKey, s.code)
    for (const [rel, targets] of Object.entries(s.relations)) for (const t of targets) sources.strandEdges.push({ from: uid('strand', spaceKey, s.code), to: uid('strand', spaceKey, t), relation: rel })
    sources.threads.push({ id: uid('thread', spaceKey, s.code), slug: s.slug, title: s.title, stageIds: s.stages.map((st) => stageId(s.code, st.band)) })
  }
  for (const e of sp.stageEdges) {
    const [fc, fb] = e.from.split(':')
    const [tc, tb] = e.to.split(':')
    sources.stageEdges.push({ from: stageId(fc, fb), to: stageId(tc, tb), relation: 'prerequisiteOf' })
  }
  const edges = T.deriveOrderEdges(sources, stages, BANDS)

  const home = SUBJECTS.find((s) => s.key === sp.homeSubject)
  const axisIds = {}
  w(`-- ${sp.slug}: ${stages.length} stages, ${edges.length} ordering claims, home subject ${home.label}`)
  for (const s of SUBJECTS) {
    const id = uid('axis', pid, `host-${s.key}`)
    axisIds[s.key] = id
    const def = T.k12TierAxis(s.tiers, s.notes)
    const name = `${s.label}: K-12 hours by grade band and year`
    const desc = `The timetable of ${s.label.toLowerCase()} with four grade bands of 3, 3, 3 and 4 years and three hour tiers (lower K-4, middle 5-8, upper 9-12). Hours are placeholders and editable. A plan on this axis counts its content against ${s.label.toLowerCase()} time.`
    const src = s.key === 'biology' ? 'Hours per year, biology: Dustin Eirdosh, 2026-10-25, revised the same day. All placeholders.' : 'Placeholder. No source. AI-drafted, unreviewed.'
    w('INSERT INTO lpm_time_axes (id, project_id, name, description, kind, definition, source, status, subject)')
    w(`VALUES (${q(id)}, ${q(pid)}, ${q(name)}, ${q(desc)}, 'generated', ${jq(def)}, ${q(src)}, 'proposed', ${q(s.key)}) ON CONFLICT (id) DO NOTHING;`)
    const aid = uid('assumption', pid, `hours-${s.key}`)
    w('INSERT INTO lpm_time_assumptions (id, project_id, plan_id, axis_id, projection_id, statement, assumption_type, confidence, source, rationale, value)')
    w(`VALUES (${q(aid)}, ${q(pid)}, NULL, ${q(id)}, NULL, ${q(s.statement)}, ${q(s.type)}, 'low', ${q(s.key === 'biology' ? 'Dustin Eirdosh, 2026-10-25.' : 'No source.')}, ${q(s.why)}, NULL) ON CONFLICT (id) DO NOTHING;`)
  }
  const homeAxis = axisIds[home.key]
  const noun = `the content of ${sp.name.replace(' LPM (Synthetic)', '')}`
  const hostWord = home.label.toLowerCase()
  const PLANS = [
    { key: 'capstone', preset: 'capstone', name: 'Starter plan: one unit at the end of each year', summary: `${noun[0].toUpperCase() + noun.slice(1)} is taught as one unit in the last part of each school year of ${hostWord}. Placeholder numbers. It shows a shape and makes no recommendation.`, extra: {} },
    { key: 'threaded', preset: 'threaded', name: 'Starter plan: a slice of every session', summary: `A slice of every ${hostWord} session links its topic to the concepts of this space, all year. Placeholder numbers. It shows a shape and makes no recommendation.`, extra: {} },
    { key: 'spiral', preset: 'spiral', name: 'Starter plan: short blocks that return each year, plus a small thread', summary: 'Two short blocks in every year and a small thread between them. Placeholder numbers. It shows a shape and makes no recommendation.', extra: { returns_per_year: 2, thread_fraction: 0.25 } },
    { key: 'sequenced', preset: 'sequenced', name: 'Starter plan: stages in sequence, in dependency order', summary: "Inside each grade band every stage takes its own stretch of the band, in the order the space's prerequisite and thread links give. Placeholder numbers. It shows a shape and makes no recommendation.", extra: { sequence_order: 'dependency' } },
    { key: 'sequenced-reverse', preset: 'sequenced', name: 'Control: the same sequence in reverse dependency order', summary: 'A negative control for the order check. It reverses the sequence on purpose so that the check has violations to find. It is not a design.', extra: { sequence_order: 'reverse' } },
  ]
  const planIds = {}
  for (const pl of PLANS) {
    const planId = uid('plan', pid, pl.key)
    planIds[pl.key] = planId
    const params = { preset: pl.preset, share: SHARE, reinforcing_share: 0.15, ...pl.extra }
    w('INSERT INTO lpm_time_plans (id, project_id, axis_id, name, summary, kind, parameters, status)')
    w(`VALUES (${q(planId)}, ${q(pid)}, ${q(homeAxis)}, ${q(pl.name)}, ${q(pl.summary)}, 'planned', ${jq(params)}, 'proposed') ON CONFLICT (id) DO NOTHING;`)
    T.generateStarterPlacements(stages, params, BANDS, edges).forEach((p, i) => {
      const id = uid('placement', planId, String(i))
      w('INSERT INTO lpm_time_placements (id, plan_id, target_type, target_id, role, resource, selector, amount, note, sort_order)')
      w(`VALUES (${q(id)}, ${q(planId)}, ${q(p.target_type)}, ${q(p.target_id)}, ${q(p.role)}, ${q(p.resource)}, ${jq(p.selector)}, ${jq(p.amount)}, ${sqlOrNull(p.note)}, ${i}) ON CONFLICT (id) DO NOTHING;`)
    })
  }

  const expected = sp.key === 'social'
    ? ['threaded', "Hypothesis from the design note, to be tested and never a recommendation. Threaded time plus spiral blocks are expected to fit this space best, because participation accumulates through sustained practice and concepts attach to cases that recur."]
    : ['sequenced', "Hypothesis from the design note, to be tested and never a recommendation. A sequenced plan with blocks for projects is expected to fit this space best, because formal prerequisites fix the order and programming practice needs unbroken time."]
  const assumptions = [
    ['capstone', `The share of ${hostWord} teaching time that this space takes is between 10 and 30 percent.`, 'placeholder', 'low', 'No source.', 'The true share is unknown. Every derived number carries the range. The same range is used for all four spaces so that they compare on equal hours.', { low: 0.1, high: 0.3 }],
    ['capstone', `${home.label} teaching is spread evenly through each year, so the last fifth of the year holds a fifth of its time.`, 'derived', 'low', 'Design note 2026-10-25, section 5.4.', 'Used to turn a position in the year into hours.', null],
    ['capstone', "Within a grade band, every stage takes an equal part of the band's time for this space.", 'derived', 'low', 'Design note 2026-10-25, section 5.5.', 'A starting rule. Stages differ in size, so equal parts are an approximation.', null],
    ['capstone', 'A topic gives 15 percent of its time to its reinforcing concepts as threaded time. Its primary concepts share the rest equally.', 'placeholder', 'low', 'No source.', 'Concept time is derived from topic time. The split is an accounting rule and makes no claim about learning.', { reinforcing_share: 0.15 }],
    ['spiral', 'The spiral plan has two blocks per year and keeps a quarter of the space\'s time as a thread.', 'placeholder', 'low', 'No source.', 'That proportion is a hypothesis to test.', { returns_per_year: 2, thread_fraction: 0.25 }],
    ['sequenced', "Inside a band, each stage takes its own stretch of the band's teaching time, in dependency order. Stages with no dependency between them are ordered by strand and then by id.", 'derived', 'low', 'Design note 2026-10-25, section 5.11.', "The links come from this space's own prerequisite claims, authored for its domain. This is a rule of the model and makes no claim about how any school should sequence.", null],
    ['sequenced-reverse', 'This plan reverses the dependency order on purpose. It is a negative control for the order check and carries no design intent.', 'derived', 'high', 'Design note 2026-10-25, section 5.11.', 'A check that never reports a violation tells us little. The control shows what a violation looks like on this space.', null],
    [expected[0], expected[1], 'placeholder', 'low', 'Design note 2026-10-25, section 8.1.', 'Hypotheses about the fit between content and delivery pattern are tested by the comparison and are not recommendations.', null],
  ]
  assumptions.forEach(([planKey, statement, type, conf, src, why, value], i) => {
    const aid = uid('assumption', pid, `plan-${i}`)
    w('INSERT INTO lpm_time_assumptions (id, project_id, plan_id, axis_id, projection_id, statement, assumption_type, confidence, source, rationale, value)')
    w(`VALUES (${q(aid)}, ${q(pid)}, ${q(planIds[planKey])}, NULL, NULL, ${q(statement)}, ${q(type)}, ${q(conf)}, ${q(src)}, ${q(why)}, ${value ? jq(value) : 'NULL'}) ON CONFLICT (id) DO NOTHING;`)
  })
  w()
}

process.stdout.write(lines.join('\n') + '\n')
