#!/usr/bin/env node
// Generates the migration that deploys four OpenEvo thinking tools (Tinbergen's Questions, Causal Mapping, Payoff Matrices,
// Analogy Mapping) across the grade bands of each of the four synthetic spaces.
//
//   node scripts/generate_thinking_tool_threads_migration.mjs scripts/data/thinking-tool-strategies.json > supabase/migrations/<n>_thinking_tool_threads.sql
//
// Each tool becomes one thread per space (thread_type vertical_horizontal, status proposed). A station attaches the tool to one
// stage of the space and says in role_note what students do with the tool there, with an example, the representation, the new
// demand beyond the band before and the concepts it develops. Each space gets one paragraph in its introduction that states the
// strategy. Sources that exist in LiteratureBase become literature_references rows of the spaces whose stations cite them.
// Input is the reviewed strategy file. Project, branch and concept ids are read live (service_role key from .supabase-secrets).
// Ids are uuid5-derived, so running again against unchanged content gives identical SQL. Everything is AI-drafted and unreviewed.

import { readFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const input = JSON.parse(readFileSync(path.resolve(process.argv[2]), 'utf8'))
const env = readFileSync(path.join(root, '.env.local'), 'utf8')
const URL_ = env.match(/VITE_SUPABASE_URL=(.*)/)[1].trim().replace(/^"|"$/g, '')
const KEY = readFileSync(path.join(root, '.supabase-secrets', 'service-role-key.txt'), 'utf8').trim()
async function rest(p) {
  const r = await fetch(`${URL_}/rest/v1/${p}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
  if (!r.ok) throw new Error(`${p}: ${r.status}`)
  return r.json()
}
const LB = process.env.LITERATUREBASE_DIR || 'D:/dev/openevo-ccs-lab/literaturebase'
const NS = uuid5('https://openevo-ccs.github.io/openlpm/thinking-tool-threads-2026-10-26', uuid5.URL)
const uid = (...parts) => uuid5(parts.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const arr = (xs) => 'ARRAY[' + xs.map(q).join(', ') + ']::text[]'
const NOTE = 'AI-drafted on 2026-10-26 from the OpenEvo Teacher\'s Guide chapter on thinking tools, the MethodsBase records of the four tools and the verified evidence listed in the thread. No subject-matter expert has reviewed it and no classroom has tested it.'
const TOOLS = {
  tinbergen: { label: "Tinbergen's Questions", method: 'OE-METHOD-tinbergens-questions' },
  causal: { label: 'Causal Mapping', method: 'OE-METHOD-causal-mapping' },
  payoff: { label: 'Payoff Matrices', method: 'OE-METHOD-payoff-matrices' },
  analogy: { label: 'Analogy Mapping', method: 'OE-METHOD-analogy-mapping' },
}
const SPACES = {
  bio: { slug: 'bio-core-lpm-synth', name: 'Bio-Core' },
  soc: { slug: 'social-core-lpm-synth', name: 'Social-Core' },
  comp: { slug: 'computational-core-lpm-synth', name: 'Computational-Core' },
  int: { slug: 'interdisciplinary-lpm-synth', name: 'Interdisciplinary' },
}
const BANDS = ['K-2', '3-5', '6-8', '9-12']
const TYPE_MAP = { 'journal-article': 'article', article: 'article', 'book-chapter': 'chapter', chapter: 'chapter', book: 'book', report: 'report', thesis: 'thesis' }
const sources = new Map((input.sources ?? []).map((s) => [s.id, s]))
// Short form of an APA citation: first surname, "and" a second, or "et al.", then the year. Titles stay out of thread text.
function shortCite(citation) {
  const m = String(citation).match(/^(.*?)\((\d{4})[a-z]?\)/)
  if (!m) return String(citation).slice(0, 60)
  const authors = m[1].split(/\.\s*,\s*(?:&\s*)?|\.\s*&\s*|\s*&\s*/).map((a) => a.trim()).filter(Boolean)
  const sur = authors.map((a) => a.split(',')[0].trim())
  const who = sur.length === 1 ? sur[0] : sur.length === 2 ? `${sur[0]} and ${sur[1]}` : `${sur[0]} et al.`
  return `${who} (${m[2]})`
}
const lines = []
const w = (s = '') => lines.push(s)
const warnings = []
const stats = { threads: 0, stations: 0, literature: 0 }

w(`-- Thinking tools across the grade bands of the four synthetic spaces.
-- Generated by scripts/generate_thinking_tool_threads_migration.mjs; do not hand-edit.
--
-- Four OpenEvo thinking tools (Tinbergen's Questions, Causal Mapping, Payoff Matrices, Analogy Mapping) become one thread each in
-- every space, with a station per use. Each space has its own strategy that follows its aim: the three disciplinary spaces keep
-- the tools inside their narrow vocabulary, and the Interdisciplinary space uses them across domains. Threads have status
-- 'proposed'. One paragraph per space is added to the project introduction. Literature rows are added only where missing.
-- Everything is AI-drafted and unreviewed by a subject expert.
-- Rollback: DELETE FROM lpm_threads WHERE slug LIKE 'thinking-tool-%' (stations go by cascade).

SET search_path = public, extensions;
`)

for (const [key, sp] of Object.entries(SPACES)) {
  const strat = input.strategies[key]
  if (!strat) throw new Error(`no strategy for ${key}`)
  const [project] = await rest(`projects?select=id,introduction&slug=eq.${sp.slug}`)
  const [branch] = await rest(`branches?select=id&project_id=eq.${project.id}&is_trunk=eq.true`)
  const els = await rest(`lpm_schema_elements?select=id,label,metadata&project_id=eq.${project.id}&element_type=eq.concept&limit=1000`)
  const conceptId = new Map(els.filter((e) => !e.metadata?.level || e.metadata.level === 'organizing' || e.metadata.level === 'extension').map((e) => [e.label, e.id]))
  const stageOf = (ref) => input.stageRefs[`${key}|${ref}`]
  w(`-- ${sp.name}`)
  const citedSources = new Set()
  for (const [tkey, tool] of Object.entries(TOOLS)) {
    const t = strat.tools[tkey]
    const threadId = uid('thread', key, tkey)
    const evidenceIds = [...new Set(t.stations.flatMap((s) => s.evidence ?? []))]
    for (const id of evidenceIds) citedSources.add(id)
    const evidenceText = evidenceIds.length
      ? `Evidence used for the stations: ${evidenceIds.map((id) => (sources.get(id) ? shortCite(sources.get(id).citation) : id)).join('; ')}.`
      : 'No evidence source is attached to the stations yet.'
    const narrative = `${tool.label} in ${sp.name}. Role in this space: ${t.role}. ${t.roleReason} Form: ${t.form} What it must not bring in: ${t.mustNotImport}`
    const evidenceNote = `${NOTE} ${evidenceText} MethodsBase record: ${tool.method}. Open checks for reviewers are listed under reviewNotes in scripts/data/thinking-tool-strategies.json.`
    w(`INSERT INTO lpm_threads (id, project_id, branch_id, slug, title, thread_type, connecting_idea, narrative, teaching_prompt, evidence_note, gaps, status)`)
    w(`VALUES (${q(threadId)}, ${q(project.id)}, ${q(branch.id)}, ${q('thinking-tool-' + tkey)}, ${q('Thinking tool: ' + tool.label)}, 'vertical_horizontal', ${q(t.form)}, ${q(narrative)}, ${q(t.teachingPrompt)}, ${q(evidenceNote)}, ${jq(t.gaps ?? [])}, 'proposed')`)
    w(`ON CONFLICT (project_id, slug) DO NOTHING;`)
    stats.threads++
    const ordered = t.stations.map((s, i) => ({ s, i })).sort((a, b) => BANDS.indexOf(a.s.band) - BANDS.indexOf(b.s.band) || a.i - b.i).map((x) => x.s)
    ordered.forEach((s, i) => {
      const stage = stageOf(s.stage)
      if (!stage) throw new Error(`${key}/${tkey}: unknown stage ${s.stage}`)
      const via = (s.concepts ?? []).map((c) => conceptId.get(c)).find(Boolean)
      for (const c of s.concepts ?? []) if (!conceptId.has(c)) warnings.push(`${key}/${tkey}: concept ${c} has no element in the live space`)
      const senses = s.senses?.length ? ` Domains: ${s.senses.join(', ')}.` : ''
      const note = `${s.band}, ${stage.title} (${s.level}). ${s.move} Example: ${s.example} Shown as: ${s.representation} New demand: ${s.challenge} Concepts: ${s.concepts.join(', ')}.${senses}`
      w(`INSERT INTO lpm_thread_stations (id, thread_id, data_object_id, sequence, role_note, via_element_id, relation_to_next)`)
      w(`VALUES (${q(uid('station', key, tkey, String(i + 1)))}, ${q(threadId)}, ${q(stage.id)}, ${i + 1}, ${q(note)}, ${via ? q(via) : 'NULL'}, ${i < ordered.length - 1 ? q('Leads into the next use of the tool.') : 'NULL'})`)
      w(`ON CONFLICT (thread_id, sequence) DO NOTHING;`)
      stats.stations++
    })
    w('')
  }
  // Introduction paragraph
  const para = `Thinking tools. Four OpenEvo thinking tools (Tinbergen's Questions, Causal Mapping, Payoff Matrices and Analogy Mapping) are deployed across the grade bands of this space as four threads named "Thinking tool: ...". ${strat.aimFit} ${strat.sequence} The threads have the status proposed. AI drafted them and no subject expert has reviewed them.`
  w(`UPDATE projects SET introduction = introduction || ${q('\n\n' + para)} WHERE id = ${q(project.id)} AND introduction NOT LIKE ${q('%Thinking tools. Four OpenEvo thinking tools%')};`)
  w('')
  // Literature rows for cited sources that exist in LiteratureBase and are missing from the space
  const have = new Set((await rest(`literature_references?select=literaturebase_id&project_id=eq.${project.id}&limit=1000`)).map((r) => r.literaturebase_id))
  for (const id of citedSources) {
    const s = sources.get(id)
    const lbid = s?.literaturebaseId
    if (!lbid || have.has(lbid)) continue
    const slug = lbid.replace(/^OE-LITERATURE-/, '')
    const f = [`${slug}.yaml`, `lit-${slug}.yaml`].map((n) => path.join(LB, 'records', n)).find((x) => existsSync(x))
    if (!f) { warnings.push(`${key}: ${lbid} not found in ${LB}`); continue }
    const rec = yaml.load(readFileSync(f, 'utf8'))
    const c = rec.citation ?? {}
    if (/,\s*not\b/i.test(c.title ?? '')) { warnings.push(`${key}: ${lbid} skipped, its title contains a construction the project style rules keep out of shared text (the thread still cites it as author and year)`); continue }
    const note = `Evidence for the thinking-tool threads of ${sp.name} (AI-drafted 2026-10-26, no expert review). ${s.supports ?? ''}`.trim()
    w(`INSERT INTO literature_references (project_id, literaturebase_id, title, authors, year, doi, venue, type, status, notes, tags)`)
    w(`SELECT ${q(project.id)}, ${q(lbid)}, ${q(c.title ?? lbid)}, ${jq(c.authors ?? [])}, ${c.year ?? 'NULL'}, ${c.doi ? q(c.doi) : 'NULL'}, ${c.venue ?? c.publisher ? q(c.venue ?? c.publisher) : 'NULL'}, ${TYPE_MAP[rec.type] ? q(TYPE_MAP[rec.type]) : 'NULL'}, 'draft', ${q(note)}, ${arr(['thinking-tools', 'proposed-link'])}`)
    w(`WHERE NOT EXISTS (SELECT 1 FROM literature_references WHERE project_id = ${q(project.id)} AND literaturebase_id = ${q(lbid)});`)
    stats.literature++
  }
  w('')
}
process.stdout.write(lines.join('\n') + '\n')
process.stderr.write(JSON.stringify(stats) + '\n')
for (const x of warnings) process.stderr.write('WARNING: ' + x + '\n')
