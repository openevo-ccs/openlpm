#!/usr/bin/env python3
"""Checks drafted German summaries of the unit nodes and writes the migration that adds them.

    python scripts/generate_unit_german_summaries_migration.py --batches <dir with in_N.json and out_N.json> --all <de_all.json> --number 223

The unit nodes of the German repositories (Bayern, Sachsen, Sachsen-Anhalt, Thueringen) had English summaries only. A model translated them
in batches. This script refuses the batch unless every key is present and each text passes the code checks: the numbers of the English text
appear in the German, no quotation marks, no run of English function words, plausible length, no banned phrasing. The migration fills
summary_de only where it is still empty, so it never overwrites a person's edit. Every node stays an LLM synthesized draft awaiting review.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENGLISH = re.compile(r"\b(the|and|of|with|to|for|is|are|their|they|which|that|from)\b", re.I)
BANNED = re.compile(r", " + r"not |not " + r"just|\b(genuine|genuinely|really|actually|honestly)\b|\btatsächlich\b|\bwirklich\b", re.I)


def q(v):
    return "'" + str(v).replace("'", "''") + "'"


def check(en, de):
    problems = []
    if '"' in de or "“" in de or "”" in de:
        problems.append("quotation marks")
    missing = set(re.findall(r"\d+", en)) - set(re.findall(r"\d+", de))
    if missing:
        problems.append(f"numbers missing: {sorted(missing)}")
    if len(ENGLISH.findall(de)) >= 3:
        problems.append("looks English")
    if not 0.55 <= len(de) / max(len(en), 1) <= 1.6:
        problems.append(f"length ratio {len(de) / len(en):.2f}")
    if BANNED.search(de):
        problems.append("banned wording")
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batches", required=True)
    ap.add_argument("--all", required=True)
    ap.add_argument("--number", required=True)
    args = ap.parse_args()
    allrows = {r["node_key"]: r for r in json.loads(Path(args.all).read_text(encoding="utf-8"))}
    got = {}
    for out in sorted(Path(args.batches).glob("out_*.json")):
        got.update(json.loads(out.read_text(encoding="utf-8")))
    errors = []
    if set(got) != set(allrows):
        errors.append(f"keys: missing {sorted(set(allrows) - set(got))[:5]}, extra {sorted(set(got) - set(allrows))[:5]}")
    for k, de in got.items():
        if k in allrows:
            for p in check(allrows[k]["summary_en"], de):
                errors.append(f"{k}: {p}")
    print(f"{len(got)} texts, {len(errors)} problems")
    for e in errors[:40]:
        print(" -", e)
    if errors:
        sys.exit(1)
    rows = [f"  ({q(allrows[k]['project'] + '-curriculum-repository')}, {q(k)}, {q(got[k])})" for k in sorted(got)]
    joined = ",\n".join(rows)
    sql = f"""-- {args.number}: German summaries for the {len(rows)} unit nodes of the German repositories (Bayern, Sachsen, Sachsen-Anhalt, Thueringen).
--
-- The unit nodes of migration 216 had English summaries only. A model translated them; code checked each text (numbers kept, no quotation marks,
-- no English run, plausible length). Filled only where summary_de is still empty, so no edit by a person is overwritten. The nodes stay
-- LLM synthesized drafts awaiting review (review_status unchanged). Running this twice changes nothing.
-- Generated by scripts/generate_unit_german_summaries_migration.py.
SET search_path = public, extensions;

UPDATE curriculum_repository_structure_nodes n
SET summary_de = v.summary_de, updated_at = now()
FROM (VALUES
{joined}
) AS v(project_slug, node_key, summary_de)
JOIN projects p ON p.slug = v.project_slug
WHERE n.project_id = p.id AND n.node_key = v.node_key AND n.summary_de IS NULL;

DO $$
DECLARE missing integer;
BEGIN
  SELECT count(*) INTO missing FROM curriculum_repository_structure_nodes n JOIN projects p ON p.id = n.project_id
  WHERE n.level = 'unit' AND n.summary_en IS NOT NULL AND n.summary_de IS NULL
    AND p.slug IN ('germany-curriculum-repository', 'saxony-curriculum-repository', 'saxony-anhalt-curriculum-repository', 'thuringia-curriculum-repository');
  IF missing <> 0 THEN
    RAISE EXCEPTION 'migration {args.number}: % unit nodes of the German repositories still have no German summary', missing;
  END IF;
END $$;
"""
    out = ROOT / "supabase" / "migrations" / f"{args.number}_unit_nodes_german_summaries.sql"
    out.write_text(sql, encoding="utf-8", newline="\n")
    print("wrote", out.name)


if __name__ == "__main__":
    main()
