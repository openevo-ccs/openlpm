#!/usr/bin/env python3
"""Makes the migration that ties EvoMentor Thuringia to the Lehrplan editions in the Thuringia Curriculum Repository.

Before: 118 of the 174 grade 5/6 goals had no link to the repository, only 27 goals carried an edition tag, the project declared no
source, and the repository record for Thuringia's grade bands did not list the single years 9 and 10.

The migration
  1. adds grade_bands and repository_record_id to project_source_declarations,
  2. sets gradeBands = 5/6, 7/8, 9, 10 on the repository's Thuringia grade-band record (mirror of deutsche-lpm PR 9),
  3. links every accepted grade 5/6 goal that has no link yet to the MNT 2026 record (relation built_from),
  4. tags goals with their edition (content.curriculum_version and content.source) where the goal is a confirmed part of the 2026
     document: all grade 5/6 goals (Susan's CSV is the MNT 2026 document) and the goals of grades 7 to 10 that the PDF match of 2026-10-30
     rated 'sure' or 'bullet'. Goals with an 'uncertain' or 'check' match and the goals without a PDF counterpart stay untagged,
  5. declares both documents as sources of the live space and the sandbox.
The goals of grades 7 to 10 are named by their CSV/EvoMentor id from scripts/data/lernziele-lehrplan-order-2026-10-30.json.

Usage: python scripts/generate_lehrplan_source_migration.py --number 215 --out supabase/migrations/215_....sql
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ap = argparse.ArgumentParser()
ap.add_argument('--number', required=True)
ap.add_argument('--out', required=True)
a = ap.parse_args()

order = json.load(open(os.path.join(ROOT, 'scripts', 'data', 'lernziele-lehrplan-order-2026-10-30.json'), encoding='utf-8'))
confirmed, left = [], []
for entries in order['bands'].values():
    for e in entries:
        (confirmed if e['certainty'] in ('sure', 'bullet') else left).append(e['key'])
confirmed = sorted(set(confirmed))
ids_sql = ', '.join("'" + k.replace("'", "''") + "'" for k in confirmed)

MNT = 'DELP-EVENT-thueringen-mnt-gymnasium-2026-erprobungsfassung'
BIO = 'DELP-EVENT-thueringen-biologie-gymnasium-2026-erprobungsfassung'
BANDREC = 'DELP-MANDATE-thueringen-doppelklassenstufe-lehrkraft-freiraum'

sql = f"""-- {a.number}: EvoMentor Thüringen is tied to the Lehrplan editions in the Thuringia Curriculum Repository.
--
-- Dustin, 2026-11-01: the grade bands must follow the Thüringen Lehrplan, and the project must be linked clearly to the curriculum
-- repository. What the check on 2026-11-01 found: 118 of the 174 grade 5/6 goals had no link to the repository (only edition-level links
-- exist, one record per edition), only 27 goals carried an edition tag, the project declared no source, and the repository record for the
-- grade bands named the combined spans (5/6, 7/8) but not the single years 9 and 10 (deutsche-lpm PR 9 adds gradeBands).
--
-- 1. project_source_declarations gets grade_bands (which bands a declared source covers) and repository_record_id (which repository
--    record it is).
-- 2. The grade-band record of the Thuringia repository gets gradeBands = 5/6, 7/8, 9, 10.
-- 3. Every accepted grade 5/6 goal of the live space without a link gets a built_from link to the MNT 2026 record. The two grade 9
--    goals with no counterpart in the 2026 document stay unlinked on purpose.
-- 4. Goals that are a confirmed part of the 2026 document get content.curriculum_version and content.source: all grade 5/6 goals and
--    {len(confirmed)} goals of grades 7 to 10 (match 'sure' or 'bullet' in the PDF match of 2026-10-30). {len(left)} PDF goals with an
--    'uncertain' or 'check' match are left untagged, as are the goals without a counterpart. Goals that already have a tag keep it.
-- 5. Both documents are declared as sources of EvoMentor Thüringen and its sandbox copy. The rights status of reusing the wording is
--    left open on purpose.
-- Running this twice changes nothing. Generated by scripts/generate_lehrplan_source_migration.py.
SET search_path = public, extensions;

ALTER TABLE project_source_declarations
  ADD COLUMN IF NOT EXISTS grade_bands TEXT[],
  ADD COLUMN IF NOT EXISTS repository_record_id UUID REFERENCES curriculum_repository_records(id) ON DELETE SET NULL;
COMMENT ON COLUMN project_source_declarations.grade_bands IS 'Grade bands of this project that the declared source covers, in the grade_band convention (5/6, 7/8, 9, 10).';
COMMENT ON COLUMN project_source_declarations.repository_record_id IS 'The Curriculum Repository record that describes the declared source, so the project can be checked against it.';

UPDATE curriculum_repository_records
SET content = jsonb_set(content, '{{gradeBands}}', '["5/6", "7/8", "9", "10"]'::jsonb), updated_at = now()
WHERE source_record_id = '{BANDREC}' AND NOT (content ? 'gradeBands')
  AND project_id = (SELECT id FROM projects WHERE slug = 'thuringia-curriculum-repository');

INSERT INTO curriculum_repository_links (project_id, data_object_id, repository_record_id, relation_type, rationale)
SELECT o.project_id, o.id, r.id, 'built_from',
       'Edition-level link added 2026-11-02: this grade 5/6 goal is part of the Lehrplan Mensch-Natur-Technik 2026 (Erprobungsfassung) and was loaded from Susan Hanisch''s CSV of that document.'
FROM lpm_data_objects o
JOIN curriculum_repository_records r
  ON r.source_record_id = '{MNT}' AND r.project_id = (SELECT id FROM projects WHERE slug = 'thuringia-curriculum-repository')
WHERE o.project_id = (SELECT id FROM projects WHERE slug = 'evomentor-thuringia')
  AND o.grade_band = '5/6' AND o.status = 'accepted'
  AND NOT EXISTS (SELECT 1 FROM curriculum_repository_links l WHERE l.data_object_id = o.id AND l.repository_record_id = r.id AND l.relation_type = 'built_from');

UPDATE lpm_data_objects o
SET content = o.content || jsonb_build_object('curriculum_version', '2026-erprobungsfassung', 'source', 'LP Thueringen MNT Gym 2026 Erprobungsfassung'), updated_at = now()
WHERE o.project_id IN (SELECT id FROM projects WHERE slug IN ('evomentor-thuringia', 'evomentor-thuringia-sandbox'))
  AND o.grade_band = '5/6' AND o.status = 'accepted' AND NOT (o.content ? 'curriculum_version');

UPDATE lpm_data_objects o
SET content = o.content || jsonb_build_object('curriculum_version', '2026-erprobungsfassung', 'source', 'LP Thueringen Bio Gym 2026 Erprobungsfassung'), updated_at = now()
WHERE o.project_id IN (SELECT id FROM projects WHERE slug IN ('evomentor-thuringia', 'evomentor-thuringia-sandbox'))
  AND o.grade_band IN ('7/8', '9', '10') AND o.status = 'accepted' AND NOT (o.content ? 'curriculum_version')
  AND o.content ->> 'id' IN ({ids_sql});

INSERT INTO project_source_declarations (project_id, source_name, format, license_or_rights_note, url, grade_bands, repository_record_id)
SELECT p.id, 'Lehrplan Mensch-Natur-Technik (MNT), Gymnasium, Klassenstufen 5/6, Thüringen 2026 (Erprobungsfassung)', 'PDF',
       'Rechtestatus der Wiederverwendung des Wortlauts noch zu klären.', r.content ->> 'sourceUrl', ARRAY['5/6'], r.id
FROM projects p
JOIN curriculum_repository_records r ON r.source_record_id = '{MNT}' AND r.project_id = (SELECT id FROM projects WHERE slug = 'thuringia-curriculum-repository')
WHERE p.slug IN ('evomentor-thuringia', 'evomentor-thuringia-sandbox')
  AND NOT EXISTS (SELECT 1 FROM project_source_declarations d WHERE d.project_id = p.id AND d.repository_record_id = r.id);

INSERT INTO project_source_declarations (project_id, source_name, format, license_or_rights_note, url, grade_bands, repository_record_id)
SELECT p.id, 'Lehrplan Biologie, Gymnasium, Klassenstufen 7/8, 9 und 10, Thüringen 2026 (Erprobungsfassung)', 'PDF',
       'Rechtestatus der Wiederverwendung des Wortlauts noch zu klären.', r.content ->> 'sourceUrl', ARRAY['7/8', '9', '10'], r.id
FROM projects p
JOIN curriculum_repository_records r ON r.source_record_id = '{BIO}' AND r.project_id = (SELECT id FROM projects WHERE slug = 'thuringia-curriculum-repository')
WHERE p.slug IN ('evomentor-thuringia', 'evomentor-thuringia-sandbox')
  AND NOT EXISTS (SELECT 1 FROM project_source_declarations d WHERE d.project_id = p.id AND d.repository_record_id = r.id);

DO $$
DECLARE untagged56 integer; unlinked56 integer; decl integer; bands boolean;
BEGIN
  SELECT count(*) INTO untagged56 FROM lpm_data_objects o
    WHERE o.project_id IN (SELECT id FROM projects WHERE slug IN ('evomentor-thuringia', 'evomentor-thuringia-sandbox'))
      AND o.grade_band = '5/6' AND o.status = 'accepted' AND NOT (o.content ? 'curriculum_version');
  SELECT count(*) INTO unlinked56 FROM lpm_data_objects o
    WHERE o.project_id = (SELECT id FROM projects WHERE slug = 'evomentor-thuringia') AND o.grade_band = '5/6' AND o.status = 'accepted'
      AND NOT EXISTS (SELECT 1 FROM curriculum_repository_links l WHERE l.data_object_id = o.id);
  SELECT count(*) INTO decl FROM project_source_declarations d
    WHERE d.repository_record_id IS NOT NULL AND d.project_id IN (SELECT id FROM projects WHERE slug IN ('evomentor-thuringia', 'evomentor-thuringia-sandbox'));
  SELECT EXISTS (SELECT 1 FROM curriculum_repository_records WHERE source_record_id = '{BANDREC}' AND content ? 'gradeBands') INTO bands;
  IF untagged56 <> 0 OR unlinked56 <> 0 OR decl <> 4 OR NOT bands THEN
    RAISE EXCEPTION 'migration {a.number}: untagged 5/6 goals %, unlinked 5/6 goals %, declarations % (want 4), gradeBands set %', untagged56, unlinked56, decl, bands;
  END IF;
END $$;
"""
open(a.out, 'w', encoding='utf-8', newline='\n').write(sql)
print(f'{len(confirmed)} goals of grades 7 to 10 named for tagging; {len(left)} PDF goals left out; written {a.out}')
