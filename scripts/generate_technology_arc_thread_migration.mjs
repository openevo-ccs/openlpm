#!/usr/bin/env node
// Generates the migration that adds one storyline thread, "From stone tools to AI", to the Interdisciplinary space.
//
//   OPENLPM_SECRET_ROOT=<checkout that holds .env.local and .supabase-secrets> LITERATUREBASE_DIR=<literaturebase checkout> \
//   node scripts/generate_technology_arc_thread_migration.mjs scripts/data/technology-arc-thread-2026-11-03.json > supabase/migrations/<n>_technology_arc_thread.sql
//
// The thread points at stages the space already has (one station each), so no stage, concept or link is created. Its status is
// 'proposed'. Literature rows are added only where the space lacks them. One paragraph is added to the project introduction.
// Project, branch, stage and concept ids are read live (service_role key). Ids are uuid5-derived, so running again against
// unchanged content gives identical SQL. Everything is AI-drafted and unreviewed by a subject expert.

import { readFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const secretRoot = process.env.OPENLPM_SECRET_ROOT || root
const input = JSON.parse(readFileSync(path.resolve(process.argv[2]), 'utf8'))
const env = readFileSync(path.join(secretRoot, '.env.local'), 'utf8')
const URL_ = env.match(/VITE_SUPABASE_URL=(.*)/)[1].trim().replace(/^"|"$/g, '')
const KEY = readFileSync(path.join(secretRoot, '.supabase-secrets', 'service-role-key.txt'), 'utf8').trim()
async function rest(p) {
  const r = await fetch(`${URL_}/rest/v1/${p}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
  if (!r.ok) throw new Error(`${p}: ${r.status}`)
  return r.json()
}
const LB = process.env.LITERATUREBASE_DIR || 'D:/dev/openevo-ccs-lab/literaturebase'
const NS = uuid5('https://openevo-ccs.github.io/openlpm/technology-arc-thread-2026-11-03', uuid5.URL)
const uid = (...parts) => uuid5(parts.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const TYPE_MAP = { 'journal-article': 'article', article: 'article', 'conference-paper': 'article', preprint: 'article', 'book-chapter': 'chapter', chapter: 'chapter', book: 'book', report: 'report', thesis: 'thesis' }
const lines = []
const w = (s = '') => lines.push(s)
const warnings = []
const stats = { threads: 0, stations: 0, literature: 0 }
const t = input.thread

const [project] = await rest(`projects?select=id,introduction&slug=eq.${input.project_slug}`)
if (!project) throw new Error(`no project ${input.project_slug}`)
const [branch] = await rest(`branches?select=id&project_id=eq.${project.id}&is_trunk=eq.true`)
const els = await rest(`lpm_schema_elements?select=id,label,metadata&project_id=eq.${project.id}&element_type=eq.concept&limit=1000`)
const conceptId = new Map(els.filter((e) => !e.metadata?.level || e.metadata.level === 'organizing' || e.metadata.level === 'extension').map((e) => [e.label, e.id]))
const threadId = uid('thread', t.slug)

w(`-- One storyline thread, "${t.title}", in the Interdisciplinary space.
-- Generated by scripts/generate_technology_arc_thread_migration.mjs; do not hand-edit.
--
-- The thread has ${t.stations.length} stations. Each station points at a stage the space already has, so no stage, concept or link is added. Status 'proposed'.
-- One paragraph is added to the project introduction and literature rows are added only where missing.
-- Everything is AI-drafted and unreviewed by a subject expert.
-- Rollback: DELETE FROM lpm_threads WHERE slug = ${q(t.slug)} AND project_id = ${q(project.id)}; (stations go by cascade)

SET search_path = public, extensions;
`)
w(`INSERT INTO lpm_threads (id, project_id, branch_id, slug, title, thread_type, connecting_idea, narrative, teaching_prompt, evidence_note, gaps, status)`)
w(`VALUES (${q(threadId)}, ${q(project.id)}, ${q(branch.id)}, ${q(t.slug)}, ${q(t.title)}, ${q(t.thread_type)}, ${q(t.connectingIdea)}, ${q(t.narrative)}, ${q(t.teachingPrompt)}, ${q(t.evidenceNote)}, ${jq(t.gaps)}, 'proposed')`)
w(`ON CONFLICT (project_id, slug) DO NOTHING;`)
stats.threads++
for (const [i, s] of t.stations.entries()) {
  const [stage] = await rest(`lpm_data_objects?select=id,title,project_id&id=eq.${s.stage}`)
  if (!stage) throw new Error(`station ${i + 1}: stage ${s.stage} not found`)
  if (stage.project_id !== project.id) throw new Error(`station ${i + 1}: stage ${stage.title} belongs to another project`)
  const via = conceptId.get(s.concept)
  if (!via) warnings.push(`station ${i + 1}: concept ${s.concept} has no element in the space`)
  const note = `${s.label}. ${stage.title}. ${s.role}`
  w(`INSERT INTO lpm_thread_stations (id, thread_id, data_object_id, sequence, role_note, via_element_id, relation_to_next)`)
  w(`VALUES (${q(uid('station', t.slug, String(i + 1)))}, ${q(threadId)}, ${q(stage.id)}, ${i + 1}, ${q(note)}, ${via ? q(via) : 'NULL'}, ${s.next ? q(s.next) : 'NULL'})`)
  w(`ON CONFLICT (thread_id, sequence) DO NOTHING;`)
  stats.stations++
}
w('')
w(`UPDATE projects SET introduction = introduction || ${q('\n\n' + input.introduction)} WHERE id = ${q(project.id)} AND introduction NOT LIKE ${q('%Technology thread. One thread, From stone tools to AI%')};`)
w('')
const have = new Set((await rest(`literature_references?select=literaturebase_id&project_id=eq.${project.id}&limit=1000`)).map((r) => r.literaturebase_id))
for (const s of input.sources) {
  const lbid = s.id
  if (have.has(lbid)) continue
  const slug = lbid.replace(/^OE-LITERATURE-/, '')
  const f = [`${slug}.yaml`, `lit-${slug}.yaml`].map((n) => path.join(LB, 'records', n)).find((x) => existsSync(x))
  if (!f) { warnings.push(`${lbid} not found in ${LB}`); continue }
  const rec = yaml.load(readFileSync(f, 'utf8'))
  const c = rec.citation ?? {}
  if (/,\s*not\b/i.test(c.title ?? '')) { warnings.push(`${lbid} skipped, its title contains a construction the project style rules keep out of shared text`); continue }
  const note = `Evidence for the technology thread (AI-drafted 2026-11-03, no expert review). ${s.supports ?? ''}`.trim()
  w(`INSERT INTO literature_references (project_id, literaturebase_id, title, authors, year, doi, venue, type, status, notes, tags)`)
  w(`SELECT ${q(project.id)}, ${q(lbid)}, ${q(c.title ?? lbid)}, ${jq(c.authors ?? [])}, ${c.year ?? 'NULL'}, ${c.doi ? q(c.doi) : 'NULL'}, ${c.venue ?? c.publisher ? q(c.venue ?? c.publisher) : 'NULL'}, ${TYPE_MAP[rec.type] ? q(TYPE_MAP[rec.type]) : 'NULL'}, 'draft', ${q(note)}, ARRAY['technology-thread']::text[]`)
  w(`WHERE NOT EXISTS (SELECT 1 FROM literature_references WHERE project_id = ${q(project.id)} AND literaturebase_id = ${q(lbid)});`)
  stats.literature++
}
process.stdout.write(lines.join('\n') + '\n')
process.stderr.write(JSON.stringify(stats) + '\n')
for (const x of warnings) process.stderr.write('WARNING: ' + x + '\n')
