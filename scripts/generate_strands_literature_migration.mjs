#!/usr/bin/env node
// Follow-up to migration 202: attaches the LiteratureBase sources to the two new Interdisciplinary strands and their eight parts.
//
//   LITERATUREBASE_DIR=<checkout of LiteratureBase main> node scripts/generate_strands_literature_migration.mjs scripts/data/schooling-language-strands-sources-2026-10-30.json > supabase/migrations/<n>_schooling_and_language_strands_sources.sql
//
// What it writes: one literature_references row per source in the Interdisciplinary project (only when missing, status draft, tagged
// 'schooling-language-strands' and 'proposed-link'), and for each strand and part the list of attached record ids and a note in
// content.literature_ids and content.sources_note. Run after the LiteratureBase pull requests merged and literaturebase_snapshot was
// refreshed (sync_literaturebase_snapshot.mjs). Everything is AI-drafted, and no expert confirmed any pairing.
// Ids of strands and parts come from the same uuid5 scheme as migration 202.

import { readFileSync } from 'node:fs'
import path from 'node:path'
import yaml from 'js-yaml'
import { v5 as uuid5 } from 'uuid'

const input = JSON.parse(readFileSync(path.resolve(process.argv[2]), 'utf8'))
const LB = process.env.LITERATUREBASE_DIR || 'D:/dev/openevo-ccs-lab/literaturebase-wt-main-sync-2026-10-30'
const PID = '371fce26-d1f3-439b-95df-0a0e38b8a824' // interdisciplinary-lpm-synth
const NS = uuid5('https://openevo-ccs.github.io/openlpm/schooling-language-strands-2026-10-30', uuid5.URL)
const uid = (...parts) => uuid5(parts.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const TYPE_MAP = { 'journal-article': 'article', article: 'article', 'book-chapter': 'chapter', chapter: 'chapter', book: 'book', 'edited-book': 'book', report: 'report', thesis: 'thesis' }
const NOTE = 'Sources attached on 2026-10-30. Each source was read from an abstract, a publisher description or a catalogue entry unless its LiteratureBase record says otherwise, and no expert has confirmed that it fits this part.'

const rec = (slug) => yaml.load(readFileSync(path.join(LB, 'records', `${slug}.yaml`), 'utf8'))
const all = [...new Set([...input.strands.schooling, ...input.strands.language])]
const lines = []
const w = (s = '') => lines.push(s)

w(`-- Sources for the two new Interdisciplinary strands (follow-up to migration 202).
-- Generated by scripts/generate_strands_literature_migration.mjs; do not hand-edit.
-- Adds ${all.length} literature rows to the Interdisciplinary project where missing, and lists the attached record ids in the content of
-- each strand and part. Everything is AI-drafted and unreviewed. No expert has confirmed any pairing of source and part.
-- Rollback: DELETE FROM literature_references WHERE project_id = ${q(PID)} AND 'schooling-language-strands' = ANY(tags);
--   UPDATE lpm_data_objects SET content = content - 'literature_ids' - 'sources_note' WHERE id IN (the strand and part ids below).

SET search_path = public, extensions;
`)

for (const slug of all) {
  const r = rec(slug)
  const c = r.citation
  const authors = (c.authors ?? []).map((a) => (typeof a === 'string' ? a : [a.family, a.given].filter(Boolean).join(', ')))
  const strandTag = input.strands.schooling.includes(slug) ? 'nature-of-schooling' : 'languages-of-being-human'
  const type = TYPE_MAP[r.type] ?? 'article'
  const id = r.id
  w('INSERT INTO literature_references (project_id, literaturebase_id, title, authors, year, doi, venue, type, status, notes, tags)')
  w(`SELECT ${q(PID)}, ${q(id)}, ${q(c.title)}, ${jq(authors)}, ${c.year ?? 'NULL'}, ${c.doi ? q(c.doi) : 'NULL'}, ${c.venue ? q(c.venue) : 'NULL'}, ${q(type)}, 'draft', ${q('Source for the ' + (strandTag === 'nature-of-schooling' ? 'Nature of Schooling' : 'Languages of Being Human') + ' strand (AI-drafted 2026-10-30, no expert review).')}, ARRAY['schooling-language-strands', ${q(strandTag)}, 'proposed-link']::text[]`)
  w(`WHERE NOT EXISTS (SELECT 1 FROM literature_references WHERE project_id = ${q(PID)} AND literaturebase_id = ${q(id)});`)
}
w('')
const ids = (slugs) => slugs.map((s) => rec(s).id)
for (const [key, slugs] of Object.entries(input.strands)) {
  w(`-- Strand: ${key}`)
  w(`UPDATE lpm_data_objects SET content = content || jsonb_build_object('literature_ids', ${jq(ids(slugs))}, 'sources_note', ${q(NOTE)}) WHERE id = ${q(uid('strand', key))};`)
}
w('')
for (const [k, slugs] of Object.entries(input.parts)) {
  const [strand, suffix] = k.split('|')
  w(`-- Part: ${strand} ${suffix}`)
  w(`UPDATE lpm_data_objects SET content = content || jsonb_build_object('literature_ids', ${jq(ids(slugs))}, 'sources_note', ${q(NOTE)}) WHERE id = ${q(uid('part', strand, suffix))};`)
}
process.stdout.write(lines.join('\n') + '\n')
process.stderr.write(`${all.length} sources, ${Object.keys(input.strands).length} strands, ${Object.keys(input.parts).length} parts\n`)
