#!/usr/bin/env python3
"""Makes migration 212: a short title for every grade 5/6 learning goal (feedback c5822635 and 64ef8431 of 2026-10-30).

Migration 203 gave each goal its full CSV wording as heading, so the goal showed twice. Susan asked for what grades 7 to 10 have:
a short title, with the exact wording of the goal below it. The wording itself (description) stays exactly as in her CSV.

Titles come from scripts/data/grade56_short_titles_2026_10_30.json: 53 are the earlier curated titles of goals whose text did not
change, 121 were drafted by Hermes (GWDG, deepseek) from the goal's own words and checked by code (only words from the goal, 2 to 9
words, distinct within a subtopic). They are AI drafts that Susan has not reviewed.

Usage: python scripts/generate_grade56_short_titles_migration.py --titles <json> --live <dump> --sandbox <dump> --out <sql>
(--live and --sandbox: output of scripts/read-project-content.mjs --format json for each project.)
"""
import argparse
import json
import re
import unicodedata

LIVE_PROJECT = '1b121ef2-96c2-43f7-aa2b-0e07b8de114a'
SANDBOX_SLUG = 'evomentor-thuringia-sandbox'


def norm(s):
    return re.sub(r'[^0-9a-zäöüß]', '', unicodedata.normalize('NFC', s or '').lower())


def sq(s):
    return "'" + s.replace("'", "''") + "'"


ap = argparse.ArgumentParser()
for name in ('titles', 'live', 'sandbox', 'out'):
    ap.add_argument('--' + name, required=True)
args = ap.parse_args()

titles, by_text, text_count = {}, {}, {}
for t in json.load(open(args.titles, encoding='utf-8')):
    titles.setdefault((norm(t['text']), norm(t['unter'])), t['title'])
    by_text.setdefault(norm(t['text']), t['title'])
    text_count[norm(t['text'])] = text_count.get(norm(t['text']), 0) + 1

stmts, report = [], []
for label, path, project_sql in (('evomentor-thuringia', args.live, f"project_id = '{LIVE_PROJECT}'"),
                                 (SANDBOX_SLUG, args.sandbox, f"project_id = (SELECT id FROM projects WHERE slug = '{SANDBOX_SLUG}')")):
    rows = [r for r in json.load(open(path, encoding='utf-8')) if r['grade_band'] == '5/6' and r['status'] == 'accepted']
    stmts.append(f'-- ===== {label} =====')
    missing = 0
    for r in rows:
        key = (norm(r['description']), norm((r['content'] or {}).get('unterthema') or ''))
        # the CSV leaves the subtopic of a few goals blank, so a goal whose wording is unique may match on the wording alone
        title = titles.get(key) or (by_text.get(key[0]) if text_count.get(key[0]) == 1 else None)
        if not title:
            missing += 1
            continue
        stmts.append(f"UPDATE lpm_data_objects SET title = {sq(title)}, content = content || jsonb_build_object('kurzbezeichnung', {sq(title)}::text), "
                     f"updated_at = now() WHERE id = '{r['id']}' AND {project_sql};")
    report.append(f'{label}: {len(rows)} goals, {len(rows) - missing} titled, {missing} without a title')

header = """-- 212: a short title for every grade 5/6 learning goal, with the exact CSV wording below it.
--
-- Susan Hanisch, feedback c5822635 and 64ef8431 (2026-10-30): migration 203 made the heading the full wording of each goal, so every
-- goal showed twice. Grades 7 to 10 have a short title above the exact wording; grade 5/6 now has the same. The wording (description)
-- is not touched. 53 titles are earlier curated titles of goals whose text did not change; 121 were drafted by Hermes (GWDG) from
-- the goal's own words and checked by code. They are AI drafts that Susan has not reviewed. Both copies (live space and sandbox)
-- get the same titles. Generated by scripts/generate_grade56_short_titles_migration.py.
SET search_path = public, extensions;

"""
open(args.out, 'w', encoding='utf-8', newline='\n').write(header + '\n'.join(stmts) + '\n')
print('\n'.join(report))
