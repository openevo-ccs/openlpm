def concepts_json(pairs):
    out_list = []
    for label, emphasis in pairs:
        cb_id, is_new = concept_ref(label)
        out_list.append({"conceptbase_id": cb_id, "label": label, "emphasis": emphasis, "new_sandbox_concept": is_new})
    return out_list


def substrand_content(sub):
    content = {
        "concepts": concepts_json(sub["concepts"]),
        "performanceIndicators": sub["performance_indicators"],
    }
    if sub.get("context_assumption"):
        content["contextAssumption"] = sub["context_assumption"]
    if sub.get("trajectory_variant"):
        tv = sub["trajectory_variant"]
        content["trajectoryVariants"] = [{
            "label": tv["label"],
            "contextAssumption": tv.get("context_assumption", ["minimal-prior-exposure"]),
            "concepts": concepts_json(tv["concepts"]),
            "performanceIndicators": tv["performance_indicators"],
        }]
    return content


def build_project_content(project_pid, project_slug, strand):
    """strand: dict with label, description, grade_band, associated_domains,
    relations (dict), substrands (list of substrand dicts). Emits data objects,
    one thread, and stations. Returns nothing; writes via emit()."""
    strand_obj_id = uid(f"data_object:{project_pid}:strand:{strand['label']}")
    sub_ids = [uid(f"data_object:{project_pid}:substrand:{s['label']}") for s in strand["substrands"]]
    thread_id = uid(f"thread:{project_pid}:{strand['label']}")

    strand_content = {
        "description": strand["description"],
        "relations": strand.get("relations", {}),
        "associatedDomains": strand.get("associated_domains", []),
    }
    emit(f"  -- Strand + {len(strand['substrands'])} substrand(s): {strand['label']}")
    emit("  INSERT INTO lpm_data_objects (id, object_type, title, description, grade_band, subject_area, content, status)")
    emit("  VALUES")
    rows = [
        f"  ({J(strand_obj_id)}, 'strand', {J(strand['label'])}, {J(strand['description'][:300])}, "
        f"{J(strand.get('grade_band',''))}, {J(', '.join(strand.get('associated_domains', [])))}, "
        f"{jsonb(strand_content)}, 'accepted')"
    ]
    for sid, sub in zip(sub_ids, strand["substrands"]):
        rows.append(
            f"  ({J(sid)}, 'substrand', {J(sub['label'])}, NULL, {J(sub['grade_band'])}, "
            f"{J(', '.join(sub.get('associated_domains', strand.get('associated_domains', []))))}, "
            f"{jsonb(substrand_content(sub))}, 'accepted')"
        )
    emit(",\n".join(rows) + "\n  ON CONFLICT (id) DO NOTHING;")
    emit("")

    emit(f"  INSERT INTO lpm_connections (project_id, from_object_id, to_object_id, relation_type, kind, rationale, status)")
    emit("  VALUES")
    conn_rows = [
        f"  ({J(project_pid)}, {J(sid)}, {J(strand_obj_id)}, 'isChildOf', 'asserted', NULL, 'accepted')"
        for sid in sub_ids
    ]
    emit(",\n".join(conn_rows) + "\n  ON CONFLICT DO NOTHING;")
    emit("")

    emit("  INSERT INTO lpm_threads (id, project_id, branch_id, slug, title, thread_type, connecting_idea, narrative, status)")
    emit("  SELECT")
    emit(f"    {J(thread_id)}, {J(project_pid)}, b.id, {J(strand['slug'])}, {J(strand['label'])}, "
         f"{J(strand.get('thread_type','vertical'))}, {J(strand['description'][:200])}, {J(strand['description'])}, 'accepted'")
    emit(f"  FROM branches b WHERE b.project_id = {J(project_pid)} AND b.is_trunk = TRUE")
    emit("  ON CONFLICT (project_id, slug) DO NOTHING;")
    emit("")

    station_rows = []
    for seq, (sid, sub) in enumerate(zip(sub_ids, strand["substrands"]), start=1):
        role_note = f"{sub['grade_band']}, {sub['label']}."
        station_rows.append(
            f"  ({J(uid(f'station:{thread_id}:{seq}'))}, {J(thread_id)}, {J(sid)}, {seq}, {J(role_note)}, NULL)"
        )
    emit("  INSERT INTO lpm_thread_stations (id, thread_id, data_object_id, sequence, role_note, relation_to_next)")
    emit("  VALUES")
    emit(",\n".join(station_rows) + "\n  ON CONFLICT (thread_id, sequence) DO NOTHING;")
    emit("")
    return strand_obj_id, sub_ids


