# ---------------------------------------------------------------------------
# Strand/substrand data objects + threads/stations, per project
# Each substrand dict: label, grade_band, concepts [(label, emphasis)],
# performance_indicators [str], trajectory_variant (optional dict, same shape
# minus trajectory_variant, folded into content.trajectoryVariants).
