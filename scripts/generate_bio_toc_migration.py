#!/usr/bin/env python3
"""Generates supabase/migrations/219_thuringia_bio_gym_2026_full_toc.sql from the table of contents of the Lehrplan Biologie Gymnasium 2026.

    python scripts/generate_bio_toc_migration.py

The table of contents was read on 2026-11-02 from the PDF a person had downloaded from the school portal (printed page numbers). The portal's
robots.txt forbids automated fetching, so no program fetched it. The original stays in a private folder outside every repository.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ED = "DE-TH/biologie-gymnasium-2026"
OLD_9 = "Stoff- und Energiewechselprozesse von Pilzen und grünen Pflanzen"
NEW_9 = "Stoff- und Energiewechselprozesse von grünen Pflanzen und Pilzen"
EIN, QUA = f"{ED}/einfuehrungsphase", f"{ED}/qualifikationsphase"
LE, VL = f"{QUA}/leben-und-energie", f"{QUA}/vielfalt-des-lebens"

# key, parent key, level, grade band, German heading as printed, English label, printed page, section number, sort order
NODES = [
    (EIN, ED, "grade_band", "11", "Einführungsphase (mit Realschulabschluss)", "Introductory phase (with Realschulabschluss)", None, "3", 11),
    (f"{EIN}/gruene-pflanzen-und-pilze", EIN, "topic", "11", NEW_9, "Matter and energy processes in green plants and fungi", "33", "3.1.1", 1),
    (f"{EIN}/oekologie", EIN, "topic", "11", "Ökologie", "Ecology", "36", "3.1.2", 2),
    (f"{EIN}/genetik", EIN, "topic", "11", "Genetik", "Genetics", "37", "3.1.3", 3),
    (f"{EIN}/evolution", EIN, "topic", "11", "Evolution", "Evolution", "41", "3.1.4", 4),
    (QUA, ED, "grade_band", "11/12", "Qualifikationsphase der gymnasialen Oberstufe", "Qualification phase of the upper secondary level", None, "4", 12),
    (LE, QUA, "topic", "11/12", "Inhaltsbereich Leben und Energie", "Content area: Life and energy", "49", "4.1.1", 1),
    (f"{LE}/cytologie", LE, "subtopic", "11/12", "Grundlagen der Cytologie", "Basics of cytology", "49", "4.1.1.1", 1),
    (f"{LE}/enzymatik", LE, "subtopic", "11/12", "Enzymatik", "Enzymology", "50", "4.1.1.2", 2),
    (f"{LE}/stoffwechsel", LE, "subtopic", "11/12", "Aufbauender und abbauender Stoffwechsel", "Anabolic and catabolic metabolism", "52", "4.1.1.3", 3),
    (f"{QUA}/informationsverarbeitung", QUA, "topic", "11/12", "Inhaltsbereich Informationsverarbeitung in Lebewesen", "Content area: Information processing in organisms", "55", "4.1.2", 2),
    (f"{QUA}/lebewesen-in-ihrer-umwelt", QUA, "topic", "11/12", "Inhaltsbereich Lebewesen in ihrer Umwelt", "Content area: Organisms in their environment", "58", "4.1.3", 3),
    (VL, QUA, "topic", "11/12", "Inhaltsbereich Vielfalt des Lebens", "Content area: Diversity of life", "61", "4.1.4", 4),
    (f"{VL}/molekulargenetik", VL, "subtopic", "11/12", "Molekulargenetische Grundlagen des Lebens", "Molecular genetic basis of life", "61", "4.1.4.1", 1),
    (f"{VL}/immunbiologie", VL, "subtopic", "11/12", "Immunbiologie", "Immunobiology", "63", "4.1.4.2", 2),
    (f"{VL}/entwicklung-des-lebens", VL, "subtopic", "11/12", "Entwicklung des Lebens", "Development of life", "65", "4.1.4.3", 3),
]
COVERAGE = ("Alle Lernbereiche der Klassenstufen 7 bis 10 und der Oberstufe stehen im Inhaltsverzeichnis. Unterthemen und Lernziele gibt es nur zu den "
            "Themen, für die EvoMentor Thüringen Lernziele hat.",
            "Every Lernbereich of grades 7 to 10 and of the upper secondary level is listed. Subtopics and goals exist only for topics that EvoMentor "
            "Thüringen has goals for.")


def q(v):
    return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"


def main():
    header = f"""-- 219: The full table of contents of the Thueringen Lehrplan Biologie Gymnasium 2026 (Erprobungsfassung) in the structure overview.
--
-- Read on 2026-11-02 from the PDF a person had downloaded from the school portal. The portal's robots.txt forbids automated fetching, so no
-- program fetched it. The original stays in a private folder outside every repository. Found by comparing the table of contents with the pilot
-- of migration 216:
-- 1. All 7 Lernbereiche of grades 7 to 10 were already in the pilot (pages 19 to 31 match). One heading differed: the Lehrplan prints
--    'Stoff- und Energiewechselprozesse von gruenen Pflanzen und Pilzen', the pilot had EvoMentor's order 'von Pilzen und gruenen Pflanzen'.
-- 2. Not in the pilot: the Einfuehrungsphase (4 Lernbereiche, pages 33 to 41) and the Qualifikationsphase of the Oberstufe (4 Inhaltsbereiche,
--    6 Lernbereiche, pages 49 to 65). They are added as headings with page numbers only: no summaries yet, no EvoMentor goals.
-- Every node is an LLM synthesized draft awaiting review (review_status ai-draft) at the summary-only tier. Running this twice changes nothing.
-- Generated by scripts/generate_bio_toc_migration.py.
SET search_path = public, extensions;

UPDATE curriculum_repository_structure_nodes n
SET label_de = {q(NEW_9)}, updated_at = now()
WHERE n.project_id = (SELECT id FROM projects WHERE slug = 'thuringia-curriculum-repository')
  AND n.node_key LIKE {q(ED + '/9/%')} AND n.level = 'topic' AND n.label_de = {q(OLD_9)};

UPDATE curriculum_repository_structure_nodes n
SET facts = n.facts || jsonb_build_object('coverage_de', {q(COVERAGE[0])}::text, 'coverage_en', {q(COVERAGE[1])}::text), updated_at = now()
WHERE n.project_id = (SELECT id FROM projects WHERE slug = 'thuringia-curriculum-repository') AND n.node_key = {q(ED)};
"""
    parts = [header]
    for depth in sorted({k.count("/") for k, *_ in NODES}):
        rows = []
        for k, par, lvl, gb, de, en, pg, sec, so in NODES:
            if k.count("/") != depth:
                continue
            rows.append("  (" + ", ".join([q(k), q(par), q(lvl), q(gb), q(de), q(en), q(f"p. {pg}" if pg else None), q('{"section": "%s"}' % sec), str(so)]) + ")")
        parts.append(
            "INSERT INTO curriculum_repository_structure_nodes (project_id, node_key, parent_id, level, subject, school_type, grade_band, sort_order, "
            "label_de, label_en, source_pages, facts, access_tier, review_status, origin)\n"
            "SELECT p.id, v.node_key, parent.id, v.level, 'biologie', 'Gymnasium', v.grade_band, v.sort_order, v.label_de, v.label_en, v.source_pages, "
            "v.facts::jsonb, 'summary-only', 'ai-draft', 'lehrplan-toc-2026-11-02'\nFROM (VALUES\n" + ",\n".join(rows) + "\n) AS v(node_key, parent_key, level, grade_band, label_de, label_en, source_pages, facts, sort_order)\n"
            "JOIN projects p ON p.slug = 'thuringia-curriculum-repository'\n"
            "JOIN curriculum_repository_structure_nodes parent ON parent.project_id = p.id AND parent.node_key = v.parent_key\n"
            "ON CONFLICT (project_id, node_key) DO NOTHING;\n")
    parts.append(f"""DO $$
DECLARE added integer; fixed integer;
BEGIN
  SELECT count(*) INTO added FROM curriculum_repository_structure_nodes WHERE origin = 'lehrplan-toc-2026-11-02';
  SELECT count(*) INTO fixed FROM curriculum_repository_structure_nodes WHERE label_de = {q(OLD_9)};
  IF added <> {len(NODES)} OR fixed <> 0 THEN
    RAISE EXCEPTION 'migration 219: % table-of-contents nodes (expected {len(NODES)}), % nodes still carry the old heading', added, fixed;
  END IF;
END $$;
""")
    out = ROOT / "supabase" / "migrations" / "219_thuringia_bio_gym_2026_full_toc.sql"
    out.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {out.name}: {len(NODES)} nodes")


if __name__ == "__main__":
    main()
