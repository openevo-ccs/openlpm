#!/usr/bin/env node
// Generates the migration that gives each of the four synthetic spaces its strategy for "information", grounded in
// Eirdosh and Hanisch (2026, in press), "Understanding Information as an Interdisciplinary Concept in Biology Education".
//
//   node scripts/generate_information_strategy_migration.mjs scripts/data/information-strategies.json > supabase/migrations/<n>_information_strategies.sql
//
// What it writes, all AI-drafted and unreviewed:
//   1. Per space one thread "Information across the grade bands" (status proposed) with a station per use. A station attaches to one
//      stage and says in role_note what students do, with an example, the paper's dimension, the concepts it develops, the thinking-tool
//      stations, Sachsen topics, KMK Basiskonzept and AI4K12 items it links to.
//   2. Proposed concepts (status proposed): rows of the space, with domain meanings for Interdisciplinary. Stage tags link the stages
//      of the stations to the new concepts.
//   3. For existing concepts, an additive metadata.information_strategy note. Accepted definitions are never changed.
//   4. Stage tags to AI4K12 competency elements that a station links to, where the space already holds the element.
//   5. One paragraph in each introduction, and literature rows for the paper and the sources the stations cite.
// Project, branch, concept and competency ids are read live (service_role key from .supabase-secrets). Ids are uuid5-derived.

import { readFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const input = JSON.parse(readFileSync(path.resolve(process.argv[2]), 'utf8'))
const env = readFileSync(path.join(root, '.env.local'), 'utf8')
const URL_ = env.match(/VITE_SUPABASE_URL=(.*)/)[1].trim().replace(/^"|"$/g, '')
const KEY = readFileSync(path.join(root, '.supabase-secrets', 'service-role-key.txt'), 'utf8').trim()
async function rest(p) {
  const r = await fetch(`${URL_}/rest/v1/${p}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
  if (!r.ok) throw new Error(`${p}: ${r.status}`)
  return r.json()
}
const LB = process.env.LITERATUREBASE_DIR || 'D:/dev/openevo-ccs-lab/literaturebase-wt-information-paper-2026-10-27'
const NS = uuid5('https://openevo-ccs.github.io/openlpm/information-strategies-2026-10-27', uuid5.URL)
const uid = (...parts) => uuid5(parts.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const arr = (xs) => 'ARRAY[' + xs.map(q).join(', ') + ']::text[]'
const slugify = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const NOTE = 'AI-drafted on 2026-10-27 from the paper by Eirdosh and Hanisch (2026, in press), the vocabulary and stages of the space, the Sachsen tagging and the thinking-tool strategy. No subject-matter expert has reviewed it and no classroom has tested it.'
const PAPER = 'OE-LITERATURE-eirdosh-hanisch-2026'
const DIM = { 1: 'structure without a sender', 2: 'systems that use information', 3: 'decentralized processing' }
const TYPE_MAP = { 'journal-article': 'article', article: 'article', 'book-chapter': 'chapter', chapter: 'chapter', book: 'book', report: 'report', thesis: 'thesis', 'conference-paper': 'article' }
const SPACES = {
  bio: { slug: 'bio-core-lpm-synth', name: 'Bio-Core', prefix: 'OE-CONCEPT-bio-core-' },
  soc: { slug: 'social-core-lpm-synth', name: 'Social-Core', prefix: 'OE-CONCEPT-social-core-' },
  comp: { slug: 'computational-core-lpm-synth', name: 'Computational-Core', prefix: 'OE-CONCEPT-computational-core-' },
  int: { slug: 'interdisciplinary-lpm-synth', name: 'Interdisciplinary', prefix: 'OE-CONCEPT-oe-interdisciplinary-' },
}
const DOMAIN_SLUG = { biology: 'biology', culture: 'culture', technology: 'technology', education: 'education', 'AI and computation': 'ai', cognition: 'cognition' }
async function snapshotIds() {
  const ids = new Set()
  for (let from = 0; ; from += 1000) {
    const page = await rest(`literaturebase_snapshot?select=id&order=id&limit=1000&offset=${from}`)
    page.forEach((r) => ids.add(r.id))
    if (page.length < 1000) break
  }
  return ids
}
const lines = []
const w = (s = '') => lines.push(s)
const warnings = []
const stats = {}
const short = (s, n) => String(s).split(/\s+/).slice(0, n).join(' ')

w(`-- Strategies for "information" in the four synthetic spaces, grounded in Eirdosh and Hanisch (2026, in press).
-- Generated by scripts/generate_information_strategy_migration.mjs; do not hand-edit.
--
-- Each space gets one thread "Information across the grade bands" with a station per use, proposed concepts where its vocabulary
-- cannot carry the strategy, stage tags to those concepts, additive notes on existing concepts, stage tags to AI4K12 elements the space
-- already holds, one introduction paragraph and literature rows. The three disciplinary spaces treat information in their own terms and
-- differ on purpose. The Interdisciplinary space joins them and states what does not carry over between domains.
-- Everything is AI-drafted, status 'proposed', unreviewed by a subject expert. Accepted definitions are not changed.
-- Rollback: DELETE FROM lpm_threads WHERE slug = 'information-across-the-bands' (stations by cascade);
--   DELETE FROM lpm_schema_elements WHERE metadata->>'information_strategy' = 'true' (new concepts and meanings, tags by cascade);
--   UPDATE lpm_schema_elements SET metadata = metadata - 'information_strategy_note' WHERE metadata ? 'information_strategy_note'.

SET search_path = public, extensions;
`)

for (const [key, sp] of Object.entries(SPACES)) {
  const st = input.strategies[key]
  if (!st) throw new Error(`no strategy for ${key}`)
  const [project] = await rest(`projects?select=id,introduction&slug=eq.${sp.slug}`)
  const [branch] = await rest(`branches?select=id&project_id=eq.${project.id}&is_trunk=eq.true`)
  const els = await rest(`lpm_schema_elements?select=id,label,element_type,metadata&project_id=eq.${project.id}&limit=2000`)
  const concept = new Map(els.filter((e) => e.element_type === 'concept' && (!e.metadata?.level || ['organizing', 'extension'].includes(e.metadata.level))).map((e) => [e.label, e.id]))
  const compByCb = new Map(els.filter((e) => e.element_type === 'competency').map((e) => [e.metadata?.competencybase_id, e]))
  const newId = new Map()
  w(`-- ${sp.name}`)
  const created = []
  // 1. New concepts (and domain meanings for Interdisciplinary)
  for (const c of st.newConcepts ?? []) {
    const id = uid('concept', key, slugify(c.label))
    newId.set(c.label, id)
    const meta = { definition: c.definition, vocabulary: key === 'int' ? 'OE-INTERDISCIPLINARY-v1.0.0' : `${sp.name.toUpperCase()}-proposed`, conceptbase_id: sp.prefix + slugify(c.label), level: 'extension', proposed_not_in_conceptbase: true, proposed_on: '2026-10-27', information_strategy: 'true', why: c.why, excludes: c.excludes, basis: c.basis ?? [], draft_note: NOTE }
    const parent = c.parent ? concept.get(c.parent) : null
    if (c.parent && !parent) warnings.push(`${key}: parent ${c.parent} of ${c.label} not found`)
    w(`INSERT INTO lpm_schema_elements (id, project_id, element_type, label, definition, parent_id, metadata, status)`)
    w(`VALUES (${q(id)}, ${q(project.id)}, 'concept', ${q(c.label)}, ${q(c.definition)}, ${parent ? q(parent) : 'NULL'}, ${jq(meta)}, 'proposed') ON CONFLICT (id) DO NOTHING;`)
    created.push(id)
    for (const [d, t] of Object.entries(c.domainSenses ?? {})) {
      const fid = uid('facet', key, slugify(c.label), DOMAIN_SLUG[d] ?? slugify(d))
      const fmeta = { level: 'discipline-facet', facet_of: c.label, definition: t, vocabulary: 'OE-INTERDISCIPLINARY-v1.0.0', conceptbase_id: `${sp.prefix}${slugify(c.label)}-${DOMAIN_SLUG[d] ?? slugify(d)}`, proposed_not_in_conceptbase: true, proposed_on: '2026-10-27', information_strategy: 'true', grounding: NOTE }
      w(`INSERT INTO lpm_schema_elements (id, project_id, element_type, label, definition, parent_id, metadata, status)`)
      w(`VALUES (${q(fid)}, ${q(project.id)}, 'concept', ${q(`${c.label} (${d})`)}, ${q(t)}, ${q(id)}, ${jq(fmeta)}, 'proposed') ON CONFLICT (id) DO NOTHING;`)
      created.push(fid)
    }
  }
  const cid = (label) => newId.get(label) ?? concept.get(label)
  // 2. Notes on existing concepts
  for (const n of st.conceptNotes ?? []) {
    const id = concept.get(n.concept)
    if (!id) { warnings.push(`${key}: concept note for unknown concept ${n.concept}`); continue }
    w(`UPDATE lpm_schema_elements SET metadata = metadata || jsonb_build_object('information_strategy_note', ${jq({ note: n.note, proposed_on: '2026-10-27', draft_note: NOTE })}) WHERE id = ${q(id)};`)
  }
  // 3. The thread and its stations
  const threadId = uid('thread', key)
  const toolStations = input.toolStations?.[key] ?? {}
  const evidenceIds = [...new Set(st.stations.flatMap((s) => s.evidence ?? []).filter((e) => e.startsWith('OE-LITERATURE-')))]
  const narrative = `Information in ${sp.name}. Sense: ${st.senseOfInformation} Boundary: ${st.boundary} Aim: ${st.aimFit} Sequence: ${st.sequence} Paper's three dimensions: structure without a sender is ${st.dimensions.structure.status} (${st.dimensions.structure.how}); systems that use information is ${st.dimensions.receivers.status} (${st.dimensions.receivers.how}); decentralized processing is ${st.dimensions.decentralized.status} (${st.dimensions.decentralized.how}) False friends: ${(st.falseFriends ?? []).join(' ')}`
  const evidenceNote = `${NOTE} Grounding paper: Eirdosh and Hanisch (2026, in press). ${evidenceIds.length ? 'Sources cited by the stations: ' + evidenceIds.map((e) => e.replace('OE-LITERATURE-', '')).join(', ') + '.' : ''} Open checks for reviewers are under reviewNotes in scripts/data/information-strategies.json.`
  w(`INSERT INTO lpm_threads (id, project_id, branch_id, slug, title, thread_type, connecting_idea, narrative, evidence_note, gaps, status)`)
  w(`VALUES (${q(threadId)}, ${q(project.id)}, ${q(branch.id)}, 'information-across-the-bands', 'Information across the grade bands', 'vertical_horizontal', ${q(st.senseOfInformation)}, ${q(narrative)}, ${q(evidenceNote)}, ${jq(st.gaps ?? [])}, 'proposed')`)
  w(`ON CONFLICT (project_id, slug) DO NOTHING;`)
  const BANDS = ['K-2', '3-5', '6-8', '9-12']
  const ordered = st.stations.map((s, i) => ({ s, i })).sort((a, b) => BANDS.indexOf(a.s.band) - BANDS.indexOf(b.s.band) || a.i - b.i).map((x) => x.s)
  const tagged = new Set()
  ordered.forEach((s, i) => {
    const stage = input.stageRefs[`${key}|${s.stage}`]
    if (!stage) throw new Error(`${key}: unknown stage ${s.stage}`)
    const via = (s.concepts ?? []).map(cid).find(Boolean)
    for (const c of s.concepts ?? []) if (!cid(c)) warnings.push(`${key}: concept ${c} has no element`)
    const tl = (s.toolLinks ?? []).map((t) => `${({ tinbergen: "Tinbergen's Questions", causal: 'Causal Mapping', payoff: 'Payoff Matrices', analogy: 'Analogy Mapping' })[t.tool]} ${t.band} (${short(toolStations[`${t.tool}|${t.band}|${t.stage}|${t.index}`] ?? t.stage, 9)})`)
    const sx = (s.sachsen ?? []).map((t) => input.sachsenTopics?.[t] ?? t)
    const parts = [`${s.band}, ${stage.title} (${s.level}, dimension ${s.dimension}: ${DIM[s.dimension]}). ${s.move} Example: ${s.example} Shown as: ${s.representation} New demand: ${s.challenge} Concepts: ${s.concepts.join(', ')}.`]
    if (s.senses?.length) parts.push(`Domains: ${s.senses.join(', ')}.`)
    if (tl.length) parts.push(`Thinking tools: ${tl.join('; ')}.`)
    if (sx.length) parts.push(`Sachsen topics: ${sx.join('; ')}.`)
    if (s.kmk?.length) parts.push(`KMK: ${s.kmk.join(', ')}.`)
    if (s.ai4k12?.length) parts.push(`AI4K12: ${s.ai4k12.map((a) => input.ai4k12Codes?.[a] ?? a).join(', ')}.`)
    w(`INSERT INTO lpm_thread_stations (id, thread_id, data_object_id, sequence, role_note, via_element_id, relation_to_next)`)
    w(`VALUES (${q(uid('station', key, String(i + 1)))}, ${q(threadId)}, ${q(stage.id)}, ${i + 1}, ${q(parts.join(' '))}, ${via ? q(via) : 'NULL'}, ${i < ordered.length - 1 ? q('Leads into the next use of information.') : 'NULL'})`)
    w(`ON CONFLICT (thread_id, sequence) DO NOTHING;`)
    // stage tags to new concepts
    for (const c of s.concepts ?? []) {
      if (!newId.has(c)) continue
      const k = `${stage.id}|${c}`
      if (tagged.has(k)) continue
      tagged.add(k)
      w(`INSERT INTO lpm_object_tags (project_id, data_object_id, schema_element_id, role) VALUES (${q(project.id)}, ${q(stage.id)}, ${q(newId.get(c))}, ${q('proposed-information-' + s.dimension)}) ON CONFLICT (data_object_id, schema_element_id) DO NOTHING;`)
    }
    // stage tags to AI4K12 elements the space already holds
    for (const a of s.ai4k12 ?? []) {
      const el = compByCb.get(a)
      if (!el) { warnings.push(`${key}: AI4K12 element ${a} is not in the space, no tag`); continue }
      const k = `${stage.id}|${a}`
      if (tagged.has(k)) continue
      tagged.add(k)
      const pair = { stage_id: stage.id, stage: `${s.stage} ${stage.title}`, relation: 'related', strength: 'weak', why: `Information station of ${key}: ${short(s.move, 20)}`, sense_differs: null, adjacent_band: false, source: 'information-strategy' }
      w(`INSERT INTO lpm_object_tags (project_id, data_object_id, schema_element_id, role) VALUES (${q(project.id)}, ${q(stage.id)}, ${q(el.id)}, 'related-weak') ON CONFLICT (data_object_id, schema_element_id) DO NOTHING;`)
      w(`UPDATE lpm_schema_elements SET metadata = jsonb_set(jsonb_set(metadata, '{aligned_stages}', coalesce(metadata->'aligned_stages', '[]'::jsonb) || ${jq([pair])}), '{alignment_state}', '"aligned"') WHERE id = ${q(el.id)} AND NOT (coalesce(metadata->'aligned_stages', '[]'::jsonb) @> ${jq([{ stage_id: stage.id }])});`)
    }
  })
  // 4. Introduction paragraph
  const para = `Information. This space treats information in its own terms. ${st.senseOfInformation} ${st.aimFit} ${st.sequence} The strategy rests on the paper by Eirdosh and Hanisch (2026, in press) and is a proposal. AI drafted it and no subject expert has reviewed it.`
  w(`UPDATE projects SET introduction = introduction || ${q('\n\n' + para)} WHERE id = ${q(project.id)} AND introduction NOT LIKE ${q('%Information. This space treats information in its own terms.%')};`)
  // 5. Literature rows
  const have = new Set((await rest(`literature_references?select=literaturebase_id&project_id=eq.${project.id}&limit=2000`)).map((r) => r.literaturebase_id))
  // literature_references.literaturebase_id has a foreign key to literaturebase_snapshot, so only records the snapshot already holds can be linked
  const inSnapshot = await snapshotIds()
  const pending = []
  for (const lbid of [PAPER, ...evidenceIds.filter((e) => e !== PAPER)]) {
    if (have.has(lbid)) continue
    if (!inSnapshot.has(lbid)) { pending.push(lbid); continue }
    const slug = lbid.replace(/^OE-LITERATURE-/, '')
    const f = [`${slug}.yaml`, `lit-${slug}.yaml`].map((n) => path.join(LB, 'records', n)).find((x) => existsSync(x))
    if (!f) { warnings.push(`${key}: ${lbid} not found in ${LB}`); continue }
    const rec = yaml.load(readFileSync(f, 'utf8'))
    const c = rec.citation ?? {}
    if (/,\s*not\b/i.test(c.title ?? '')) { warnings.push(`${key}: ${lbid} skipped, its title contains a construction the style rules keep out of shared text`); continue }
    const role = lbid === PAPER ? 'Grounding paper of the information strategy' : 'Source cited by the information strategy'
    w(`INSERT INTO literature_references (project_id, literaturebase_id, title, authors, year, doi, venue, type, status, notes, tags)`)
    w(`SELECT ${q(project.id)}, ${q(lbid)}, ${q(c.title ?? lbid)}, ${jq(c.authors ?? [])}, ${c.year ?? 'NULL'}, ${c.doi ? q(c.doi) : 'NULL'}, ${c.venue ?? c.publisher ? q(c.venue ?? c.publisher) : 'NULL'}, ${TYPE_MAP[rec.type] ? q(TYPE_MAP[rec.type]) : 'NULL'}, 'draft', ${q(`${role} of ${sp.name} (AI-drafted 2026-10-27, no expert review).`)}, ${arr(['information', 'proposed-link'])}`)
    w(`WHERE NOT EXISTS (SELECT 1 FROM literature_references WHERE project_id = ${q(project.id)} AND literaturebase_id = ${q(lbid)});`)
  }
  if (pending.length) { w(`-- Not linked yet, absent from literaturebase_snapshot (add after the LiteratureBase pull request merges and the snapshot syncs): ${pending.join(', ')}`); warnings.push(`${key}: ${pending.length} literature row(s) wait for the snapshot`) }
  w('')
  stats[key] = { stations: st.stations.length, newConcepts: (st.newConcepts ?? []).length, notes: (st.conceptNotes ?? []).length, rows: created.length, evidence: evidenceIds.length }
}
process.stdout.write(lines.join('\n') + '\n')
process.stderr.write(JSON.stringify(stats) + '\n')
for (const x of warnings) process.stderr.write('WARNING: ' + x + '\n')
