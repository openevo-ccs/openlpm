#!/usr/bin/env node
// Generates the migration that adds review questions for the two extension strands of the Interdisciplinary model
// (The Nature of Schooling, The Languages of Being Human), in the form of migration 199.
//
//   node scripts/generate_strands_review_agenda_migration.mjs scripts/data/review-agenda-extension-strands-2026-10-30.json > supabase/migrations/<n>_review_agenda_for_extension_strands.sql
//
// Each question is a discussion topic that points at one exact part or concept, with one of the five types from the lab's own
// theory records (aim and theory, boundary, order of steps, sources, how progress shows), plus one "About" statement that says what
// the strands are for, what is held fixed, what varies and what they can and cannot say. The migration resolves links by project
// slug, part title and concept label, stops with an error if a target is missing or matches more than one record, and skips a topic
// that already exists with the same title in the same space, so it is safe to run twice. It adds no review assignments.
// The Discussions page lists newest first, so each row gets a timestamp one second earlier than the row before it.

import { readFileSync } from 'node:fs'
import path from 'node:path'

const input = JSON.parse(readFileSync(path.resolve(process.argv[2]), 'utf8'))
const rows = input.rows.map((r) => {
  const out = { space: input.space, category: r.category, title: r.title, description: r.raw ? r.description : `${r.description}\n\n${input.closing}` }
  if (r.kind) { out.kind = r.kind; out.anchor = r.anchor }
  return out
})
const json = JSON.stringify(rows)
if (json.includes('$q$')) throw new Error('row text contains the dollar-quote marker')
const n = rows.length

process.stdout.write(`-- Review questions for the two extension strands of the Interdisciplinary model: one "About" statement and ${n - 1} questions.
-- Generated by scripts/generate_strands_review_agenda_migration.mjs; do not hand-edit.
--
-- Why. Expert review happens inside the spaces. Each question is a discussion topic that points at one exact part or concept and carries
-- one of five types taken from the lab's own theory records: aim and theory, boundary, order of steps, sources, how progress shows.
-- The "About" statement says what the strands are for, what is held fixed, what varies and what they can and cannot say.
-- What it does. Resolves each link by project slug, part title and concept label, and stops with an error if any target is missing or
-- matches more than one record. Skips a topic that already exists with the same title in the same space, so it is safe to run twice.
-- It adds no review assignments, because no reviewer is named yet. Each row gets a timestamp one second earlier than the row before it,
-- so the About statement comes first on the Discussions page.
-- Everything is AI-drafted. No expert wrote or checked a question.
-- Rollback: DELETE FROM discussion_topics WHERE project_id = (SELECT id FROM projects WHERE slug = '${input.space}') AND title IN (the titles in the list below).

SET search_path = public, extensions;

DO $MIGRATION$
DECLARE
  v_rows JSONB := $q$${json}$q$;
  r JSONB;
  v_project UUID;
  v_link UUID;
  v_n INTEGER;
  v_added INTEGER := 0;
  v_i INTEGER := 0;
BEGIN
  FOR r IN SELECT * FROM jsonb_array_elements(v_rows) LOOP
    SELECT id INTO v_project FROM projects WHERE slug = r ->> 'space';
    IF v_project IS NULL THEN
      RAISE EXCEPTION 'Project % not found', r ->> 'space';
    END IF;

    v_link := NULL;
    IF r ->> 'kind' = 'part' THEN
      SELECT count(*), min(id::text)::uuid INTO v_n, v_link FROM lpm_data_objects WHERE project_id = v_project AND title = r ->> 'anchor';
      IF v_n <> 1 THEN RAISE EXCEPTION 'Part "%" in % matches % records', r ->> 'anchor', r ->> 'space', v_n; END IF;
    ELSIF r ->> 'kind' = 'concept' THEN
      SELECT count(*), min(id::text)::uuid INTO v_n, v_link FROM lpm_schema_elements WHERE project_id = v_project AND element_type = 'concept' AND label = r ->> 'anchor';
      IF v_n <> 1 THEN RAISE EXCEPTION 'Concept "%" in % matches % records', r ->> 'anchor', r ->> 'space', v_n; END IF;
    END IF;

    v_i := v_i + 1;
    IF NOT EXISTS (SELECT 1 FROM discussion_topics WHERE project_id = v_project AND title = r ->> 'title') THEN
      INSERT INTO discussion_topics (project_id, title, description, category, linked_type, linked_id, created_at, updated_at)
      VALUES (v_project, r ->> 'title', r ->> 'description', r ->> 'category',
              CASE r ->> 'kind' WHEN 'part' THEN 'data_object' WHEN 'concept' THEN 'schema_element' ELSE NULL END,
              v_link, now() - v_i * interval '1 second', now() - v_i * interval '1 second');
      v_added := v_added + 1;
    END IF;
  END LOOP;
  RAISE NOTICE 'Review agenda for the extension strands: % topics added (${n} expected on first run)', v_added;
END
$MIGRATION$;
`)
process.stderr.write(`${n} rows\n`)
