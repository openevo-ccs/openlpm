#!/usr/bin/env node
// Generates the migration that extends the Interdisciplinary vocabulary with carefully crafted multi-domain definitions.
//
//   node scripts/generate_interdisciplinary_extension_migration.mjs scripts/data/interdisciplinary-extension.json > supabase/migrations/<n>_interdisciplinary_vocabulary_extension.sql
//
// Why: the Interdisciplinary space exists to define core concepts such as selection, information and adaptation in a general,
// multi-domain way and to make the differences between domains explicit. The narrow Core spaces keep to one discipline. Before this
// extension only Selection and Inheritance had separate domain meanings, and many concepts the Cores define (adaptation, population,
// group, model, algorithm, feedback) had no Interdisciplinary counterpart.
//
// What it writes, all AI-drafted and unreviewed:
//   1. New concepts as lpm_schema_elements rows (status proposed, level 'extension') under the best-fitting organizing concept.
//   2. Domain meanings as child rows (level 'discipline-facet', status proposed), for new concepts and for existing concepts.
//      A Core concept that is better handled as a domain meaning of a general concept (folded) gets no row of its own. It is recorded
//      in the host concept's metadata (folded_core_concepts) so the mapping survives and no domain has two facets.
//   3. For existing accepted concepts, an additive metadata.proposed_extension object (proposed wording, what does not carry over,
//      Core counterparts). The accepted definition itself is never changed.
//   4. One added paragraph in the Interdisciplinary introduction that states the aim.
// Input is the reviewed draft file. Live concepts are read with the service_role key from .supabase-secrets (never printed).
// Ids are uuid5-derived, so running again against unchanged content gives identical SQL.

import { readFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const input = JSON.parse(readFileSync(path.resolve(process.argv[2]), 'utf8'))
const env = readFileSync(path.join(root, '.env.local'), 'utf8')
const URL_ = env.match(/VITE_SUPABASE_URL=(.*)/)[1].trim().replace(/^"|"$/g, '')
const KEY = readFileSync(path.join(root, '.supabase-secrets', 'service-role-key.txt'), 'utf8').trim()
async function rest(p) {
  const r = await fetch(`${URL_}/rest/v1/${p}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
  if (!r.ok) throw new Error(`${p}: ${r.status}`)
  return r.json()
}

const PID = '371fce26-d1f3-439b-95df-0a0e38b8a824' // interdisciplinary-lpm-synth
const VOCAB = 'OE-INTERDISCIPLINARY-v1.0.0'
const NS = uuid5('https://openevo-ccs.github.io/openlpm/interdisciplinary-extension-2026-10-25', uuid5.URL)
const uid = (...parts) => uuid5(parts.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const slugify = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const NOTE = 'AI-drafted on 2026-10-25 from the Core vocabularies, the concept crosswalk and the Sachsen tagging evidence. No subject-matter expert has reviewed it.'
const DOMAIN_SLUG = { biology: 'biology', culture: 'culture', technology: 'technology', education: 'education', 'AI and computation': 'ai', cognition: 'cognition' }

const els = await rest(`lpm_schema_elements?select=id,label,metadata,status,parent_id&project_id=eq.${PID}&element_type=eq.concept&limit=500`)
const byLabel = new Map(els.filter((e) => !e.metadata?.level || e.metadata.level === 'organizing').map((e) => [e.label, e]))
const facetLabels = new Set(els.filter((e) => e.metadata?.level === 'discipline-facet').map((e) => e.label))
const lines = []
const createdIds = []
const w = (s = '') => lines.push(s)
const stats = { newConcepts: 0, facets: 0, extended: 0, folded: 0, none: 0 }

w(`-- Interdisciplinary vocabulary extension: carefully crafted multi-domain definitions of the concepts the narrow Cores also define.
-- Generated by scripts/generate_interdisciplinary_extension_migration.mjs; do not hand-edit.
--
-- The Interdisciplinary space defines core concepts in a general, multi-domain way and states what differs between domains.
-- This adds proposed concepts, proposed domain meanings and proposed wording for existing concepts. Accepted definitions are not changed.
-- Everything is AI-drafted, status 'proposed', unreviewed by a subject expert.

SET search_path = public, extensions;
`)

const conceptId = new Map() // label -> id for new and existing
for (const e of els) if (byLabel.has(e.label) && byLabel.get(e.label) === e) conceptId.set(e.label, e.id)
const entries = input.entries
for (const e of entries.filter((x) => x.action === 'new')) conceptId.set(e.label, uid('concept', slugify(e.label)))

const foldsByHost = new Map()
for (const e of entries.filter((x) => x.action === 'fold')) {
  if (!conceptId.has(e.foldedInto)) throw new Error(`${e.label}: folds into unknown concept ${e.foldedInto}`)
  if (!foldsByHost.has(e.foldedInto)) foldsByHost.set(e.foldedInto, [])
  foldsByHost.get(e.foldedInto).push({ core_concept: e.label, core_counterparts: e.coreCounterparts.map((c) => ({ space: c.space, label: c.label, relation: c.relation })), reason: e.reason, confidence: e.confidence })
}
const foldsOf = (label) => (foldsByHost.has(label) ? { folded_core_concepts: foldsByHost.get(label) } : {})
const handledHosts = new Set()
function counterparts(e) { return e.coreCounterparts.map((c) => ({ space: c.space, label: c.label, relation: c.relation })) }
function facetRow(parentLabel, domain, text, extra) {
  const label = `${extra.label ?? parentLabel} (${domain})`
  if (facetLabels.has(label)) return // the facet exists already from migration 178
  const slug = `${slugify(parentLabel)}-${extra.label ? slugify(extra.label) + '-' : ''}${DOMAIN_SLUG[domain]}`
  const meta = { level: 'discipline-facet', facet_of: parentLabel, definition: text, vocabulary: VOCAB, conceptbase_id: `OE-CONCEPT-oe-interdisciplinary-${slug}`, proposed_not_in_conceptbase: true, proposed_on: '2026-10-25', grounding: extra.grounding ?? NOTE, ...(extra.label ? { folded_from_core_concept: extra.label } : {}) }
  createdIds.push(uid('facet', slug))
  w('INSERT INTO lpm_schema_elements (id, project_id, element_type, label, definition, parent_id, metadata, status)')
  w(`VALUES (${q(uid('facet', slug))}, ${q(PID)}, 'concept', ${q(label)}, ${q(text)}, ${q(conceptId.get(parentLabel))}, ${jq(meta)}, 'proposed') ON CONFLICT (id) DO NOTHING;`)
  stats.facets++
}

for (const e of entries) {
  if (e.action === 'no-extension') { stats.none++; continue }
  if (e.action === 'new') {
    const orgRow = byLabel.get(e.organizing)
    if (!orgRow) throw new Error(`${e.label}: unknown organizing concept ${e.organizing}`)
    const meta = { definition: e.general, vocabulary: VOCAB, conceptbase_id: `OE-CONCEPT-oe-interdisciplinary-${slugify(e.label)}`, level: 'extension', proposed_not_in_conceptbase: true, proposed_on: '2026-10-25', excludes: e.excludes, core_counterparts: counterparts(e), curriculum_use: e.curriculumUse, grounding: e.grounding, confidence: e.confidence, draft_note: NOTE, ...foldsOf(e.label) }
    handledHosts.add(e.label)
    w(`-- New concept: ${e.label}`)
    createdIds.push(conceptId.get(e.label))
    w('INSERT INTO lpm_schema_elements (id, project_id, element_type, label, definition, parent_id, metadata, status)')
    w(`VALUES (${q(conceptId.get(e.label))}, ${q(PID)}, 'concept', ${q(e.label)}, ${q(e.general)}, ${q(orgRow.id)}, ${jq(meta)}, 'proposed') ON CONFLICT (id) DO NOTHING;`)
    stats.newConcepts++
    for (const [d, t] of Object.entries(e.facets)) facetRow(e.label, d, t, {})
    w('')
  } else if (e.action === 'add-facets') {
    const row = byLabel.get(e.label)
    if (!row) throw new Error(`${e.label}: no live concept to extend`)
    const ext = { proposed_on: '2026-10-25', general: e.general, excludes: e.excludes, core_counterparts: counterparts(e), curriculum_use: e.curriculumUse, grounding: e.grounding, confidence: e.confidence, draft_note: NOTE, ...foldsOf(e.label) }
    handledHosts.add(e.label)
    w(`-- Extended concept: ${e.label}`)
    w(`UPDATE lpm_schema_elements SET metadata = metadata || jsonb_build_object('proposed_extension', ${jq(ext)}) WHERE id = ${q(row.id)};`)
    stats.extended++
    for (const [d, t] of Object.entries(e.facets)) facetRow(e.label, d, t, {})
    w('')
  } else if (e.action === 'fold') {
    stats.folded++
  }
}

// Hosts that have folds and no entry of their own (for example Selection) get their mapping as additive metadata.
for (const [host, list] of foldsByHost) {
  if (handledHosts.has(host)) continue
  const row = byLabel.get(host)
  if (!row) throw new Error(`${host}: no live concept to hold folded Core concepts`)
  w(`-- Core concepts handled as domain meanings of ${host}`)
  w(`UPDATE lpm_schema_elements SET metadata = metadata || jsonb_build_object('proposed_extension', coalesce(metadata->'proposed_extension', '{}'::jsonb) || ${jq({ proposed_on: '2026-10-25', draft_note: NOTE, folded_core_concepts: list })}) WHERE id = ${q(row.id)};`)
  w('')
}

if (input.introAddition) {
  w('-- Introduction: state the aim of the space')
  w(`UPDATE projects SET introduction = introduction || ${q('\n\n' + input.introAddition)} WHERE id = ${q(PID)} AND introduction NOT LIKE ${q('%' + input.introAddition.slice(0, 40) + '%')};`)
  w('')
}
w('-- ROLLBACK (run by hand if the extension should be removed):')
w(`--   DELETE FROM lpm_schema_elements WHERE id IN (${createdIds.map(q).join(', ')});`)
w(`--   UPDATE lpm_schema_elements SET metadata = metadata - 'proposed_extension' WHERE project_id = ${q(PID)} AND metadata ? 'proposed_extension';`)
w('--   (The introduction paragraph is removed by editing the project introduction by hand.)')
process.stdout.write(lines.join('\n') + '\n')
process.stderr.write(`${JSON.stringify(stats)}\n`)
