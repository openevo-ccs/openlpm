#!/usr/bin/env node
// Generates supabase/migrations/176_time_layer.sql: the time-layer tables, their access rules, the discussion
// link types, and starter axes, plans, assumptions and a projection for bio-core-lpm-synth and
// interdisciplinary-lpm-synth.
//
// Design source: lab_manager/docs/design-notes/
// bio-core-interdisciplinary-modelling-literature-human-examples-and-time-budget-2026-10-25.md (section 5).
//
// The starter placements come from src/lib/time (bundled here with esbuild) and the live stage ids come from
// the database (service_role key from .supabase-secrets, never printed). Ids are uuid5-derived, so re-running
// against unchanged content gives identical SQL.
//
//   node scripts/generate_time_layer_migration.mjs > supabase/migrations/176_time_layer.sql

import { build } from 'esbuild'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const dir = mkdtempSync(path.join(tmpdir(), 'time-seed-'))
const out = path.join(dir, 'time.mjs')
await build({ entryPoints: [path.join(root, 'src/lib/time/index.ts')], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error' })
const T = await import(pathToFileURL(out).href)
rmSync(dir, { recursive: true, force: true })

const env = readFileSync(path.join(root, '.env.local'), 'utf8')
const URL_ = env.match(/VITE_SUPABASE_URL=(.*)/)[1].trim().replace(/^"|"$/g, '')
const KEY = readFileSync(path.join(root, '.supabase-secrets', 'service-role-key.txt'), 'utf8').trim()
async function rest(p) {
  const r = await fetch(`${URL_}/rest/v1/${p}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
  if (!r.ok) throw new Error(`${p}: ${r.status}`)
  return r.json()
}

const NS = uuid5('https://openevo-ccs.github.io/openlpm/time-layer-2026-10-25', uuid5.URL)
const uid = (...parts) => uuid5(parts.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const sqlOrNull = (v) => (v === null || v === undefined ? 'NULL' : q(v))

const PROJECTS = {
  'bio-core-lpm-synth': '28997544-0d87-4b05-9ee2-7c474513c108',
  'interdisciplinary-lpm-synth': '371fce26-d1f3-439b-95df-0a0e38b8a824',
}

const lines = []
const w = (s = '') => lines.push(s)
// Rows as JSON, for testing the page before the migration is pushed:  --fixtures <path>
const fx = { axes: [], plans: [], placements: [], projections: [], assumptions: [] }

w(`-- Time layer: axes, plans, placements, assumptions and projections.
-- Generated by scripts/generate_time_layer_migration.mjs; do not hand-edit.
--
-- LPM content stays free of time. These tables hold time separately:
--   lpm_time_axes         a sequence of discrete units (levels from coarse to fine, optional dates)
--   lpm_time_plans        a named plan on one axis (planned, pathway, scheduled or observed)
--   lpm_time_placements   content placed onto units of the axis, with an amount
--   lpm_time_assumptions  every number or rule a plan rests on, each with a type, confidence, source and a
--                         discussion thread
--   lpm_time_projections  a mapping from one axis (for example a generic 365-day year) onto another (a dated
--                         school year), with a computed fit report in the app
-- Open vocabularies are TEXT columns, following this schema's convention. Nothing derived is stored.
--
-- Everything seeded below is AI-drafted, status 'proposed', and every hour figure is a placeholder.

SET search_path = public, extensions;

CREATE TABLE IF NOT EXISTS lpm_time_axes (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  description TEXT,
  -- Open vocabulary: generated, generic-year, dated, explicit.
  kind TEXT NOT NULL DEFAULT 'generated',
  definition JSONB NOT NULL,
  -- Optional place code, matching the Curriculum Repository's places.
  jurisdiction TEXT,
  source TEXT,
  status TEXT NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed', 'under_review', 'accepted', 'rejected')),
  created_by UUID REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lpm_time_plans (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  axis_id UUID NOT NULL REFERENCES lpm_time_axes(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  summary TEXT,
  -- Open vocabulary: planned, pathway, scheduled, observed.
  kind TEXT NOT NULL DEFAULT 'planned',
  -- Preset and measure parameters (share, returns per year, reinforcing share). Placements are the source of truth.
  parameters JSONB NOT NULL DEFAULT '{}'::jsonb,
  forked_from UUID REFERENCES lpm_time_plans(id) ON DELETE SET NULL,
  valid_from DATE,
  valid_to DATE,
  status TEXT NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed', 'under_review', 'accepted', 'rejected')),
  created_by UUID REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lpm_time_placements (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  plan_id UUID NOT NULL REFERENCES lpm_time_plans(id) ON DELETE CASCADE,
  -- Open vocabulary: topic, concept, thread, strand, method, competency, assessment_item, project, ...
  target_type TEXT NOT NULL,
  -- TEXT because a target can be a row id or a ConceptBase id.
  target_id TEXT NOT NULL,
  -- dedicated or threaded.
  role TEXT,
  resource TEXT NOT NULL DEFAULT 'instructional_time',
  selector JSONB NOT NULL,
  amount JSONB NOT NULL,
  note TEXT,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lpm_time_projections (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  source_axis_id UUID NOT NULL REFERENCES lpm_time_axes(id) ON DELETE CASCADE,
  target_axis_id UUID NOT NULL REFERENCES lpm_time_axes(id) ON DELETE CASCADE,
  -- Open vocabulary: date-offset, teaching-time, landmarks.
  rule TEXT NOT NULL DEFAULT 'teaching-time',
  parameters JSONB NOT NULL DEFAULT '{}'::jsonb,
  source TEXT,
  status TEXT NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed', 'under_review', 'accepted', 'rejected')),
  created_by UUID REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS lpm_time_assumptions (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  plan_id UUID REFERENCES lpm_time_plans(id) ON DELETE CASCADE,
  axis_id UUID REFERENCES lpm_time_axes(id) ON DELETE CASCADE,
  projection_id UUID REFERENCES lpm_time_projections(id) ON DELETE CASCADE,
  statement TEXT NOT NULL,
  -- Open vocabulary: estimate, literature, derived, placeholder, calendar-constraint.
  assumption_type TEXT NOT NULL DEFAULT 'placeholder',
  -- low, medium or high.
  confidence TEXT NOT NULL DEFAULT 'low' CHECK (confidence IN ('low', 'medium', 'high')),
  source TEXT,
  rationale TEXT,
  value JSONB,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'under_review', 'accepted', 'contested', 'retired')),
  reviewed_at TIMESTAMPTZ,
  created_by UUID REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_lpm_time_axes_project ON lpm_time_axes(project_id);
CREATE INDEX IF NOT EXISTS idx_lpm_time_plans_project ON lpm_time_plans(project_id);
CREATE INDEX IF NOT EXISTS idx_lpm_time_plans_axis ON lpm_time_plans(axis_id);
CREATE INDEX IF NOT EXISTS idx_lpm_time_placements_plan ON lpm_time_placements(plan_id);
CREATE INDEX IF NOT EXISTS idx_lpm_time_assumptions_project ON lpm_time_assumptions(project_id);
CREATE INDEX IF NOT EXISTS idx_lpm_time_assumptions_plan ON lpm_time_assumptions(plan_id);
CREATE INDEX IF NOT EXISTS idx_lpm_time_projections_project ON lpm_time_projections(project_id);

ALTER TABLE lpm_time_axes ENABLE ROW LEVEL SECURITY;
ALTER TABLE lpm_time_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE lpm_time_placements ENABLE ROW LEVEL SECURITY;
ALTER TABLE lpm_time_projections ENABLE ROW LEVEL SECURITY;
ALTER TABLE lpm_time_assumptions ENABLE ROW LEVEL SECURITY;

-- Members read. Owners, maintainers, editors and contributors write (is_project_editor, migration 135).
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['lpm_time_axes', 'lpm_time_plans', 'lpm_time_projections', 'lpm_time_assumptions'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS "Project members can view %1$s" ON %1$I', t);
    EXECUTE format('CREATE POLICY "Project members can view %1$s" ON %1$I FOR SELECT USING (is_project_member(project_id))', t);
    EXECUTE format('DROP POLICY IF EXISTS "Project editors can create %1$s" ON %1$I', t);
    EXECUTE format('CREATE POLICY "Project editors can create %1$s" ON %1$I FOR INSERT WITH CHECK (is_project_editor(project_id))', t);
    EXECUTE format('DROP POLICY IF EXISTS "Project editors can update %1$s" ON %1$I', t);
    EXECUTE format('CREATE POLICY "Project editors can update %1$s" ON %1$I FOR UPDATE USING (is_project_editor(project_id)) WITH CHECK (is_project_editor(project_id))', t);
    EXECUTE format('DROP POLICY IF EXISTS "Project editors can delete %1$s" ON %1$I', t);
    EXECUTE format('CREATE POLICY "Project editors can delete %1$s" ON %1$I FOR DELETE USING (is_project_editor(project_id))', t);
  END LOOP;
END $$;

-- Placements have no project_id of their own; access follows the plan.
DROP POLICY IF EXISTS "Project members can view lpm_time_placements" ON lpm_time_placements;
CREATE POLICY "Project members can view lpm_time_placements" ON lpm_time_placements FOR SELECT
  USING (EXISTS (SELECT 1 FROM lpm_time_plans p WHERE p.id = plan_id AND is_project_member(p.project_id)));
DROP POLICY IF EXISTS "Project editors can create lpm_time_placements" ON lpm_time_placements;
CREATE POLICY "Project editors can create lpm_time_placements" ON lpm_time_placements FOR INSERT
  WITH CHECK (EXISTS (SELECT 1 FROM lpm_time_plans p WHERE p.id = plan_id AND is_project_editor(p.project_id)));
DROP POLICY IF EXISTS "Project editors can update lpm_time_placements" ON lpm_time_placements;
CREATE POLICY "Project editors can update lpm_time_placements" ON lpm_time_placements FOR UPDATE
  USING (EXISTS (SELECT 1 FROM lpm_time_plans p WHERE p.id = plan_id AND is_project_editor(p.project_id)))
  WITH CHECK (EXISTS (SELECT 1 FROM lpm_time_plans p WHERE p.id = plan_id AND is_project_editor(p.project_id)));
DROP POLICY IF EXISTS "Project editors can delete lpm_time_placements" ON lpm_time_placements;
CREATE POLICY "Project editors can delete lpm_time_placements" ON lpm_time_placements FOR DELETE
  USING (EXISTS (SELECT 1 FROM lpm_time_plans p WHERE p.id = plan_id AND is_project_editor(p.project_id)));

-- Each assumption and each plan can carry a discussion thread (same widening as migration 156).
ALTER TABLE discussion_topics DROP CONSTRAINT IF EXISTS discussion_topics_linked_type_check;
ALTER TABLE discussion_topics ADD CONSTRAINT discussion_topics_linked_type_check
  CHECK (linked_type IN ('schema_element', 'data_object', 'literature_reference', 'base_repo_record', 'time_assumption', 'time_plan'));
`)

// ---- seeds ----
const AXIS_SOURCE = 'Hours per year: Dustin Eirdosh, 2026-10-25 (lower grades 15-45, upper grades 100-150; middle 40-80 as the default he gave). All placeholders.'
