#!/usr/bin/env node
// Generates the migration that adds two plans per synthetic LPM on the K-12 axis seeded by migration 176:
//   1. stages in sequence, in dependency order inside each band
//   2. the same sequence in reverse dependency order, a negative control for the order check
// The order comes from the space's own sequencing claims (prerequisite and foundational links between strands
// and stages, thread order, grade-band order), read from the live database with the service_role key from
// .supabase-secrets (never printed). Ids are uuid5-derived, so re-running gives identical SQL.
//
//   node scripts/generate_sequenced_plans_migration.mjs > supabase/migrations/177_sequenced_plans.sql

import { build } from 'esbuild'
import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { v5 as uuid5 } from 'uuid'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const dir = mkdtempSync(path.join(tmpdir(), 'seq-seed-'))
const out = path.join(dir, 'time.mjs')
await build({ entryPoints: [path.join(root, 'src/lib/time/index.ts')], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error' })
const T = await import(pathToFileURL(out).href)
rmSync(dir, { recursive: true, force: true })

const env = readFileSync(path.join(root, '.env.local'), 'utf8')
const URL_ = env.match(/VITE_SUPABASE_URL=(.*)/)[1].trim().replace(/^"|"$/g, '')
const KEY = readFileSync(path.join(root, '.supabase-secrets', 'service-role-key.txt'), 'utf8').trim()
async function rest(p) {
  const r = await fetch(`${URL_}/rest/v1/${p}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } })
  if (!r.ok) throw new Error(`${p}: ${r.status}`)
  return r.json()
}

// Same namespace as migration 176, so the axis ids match the rows that migration created.
const NS = uuid5('https://openevo-ccs.github.io/openlpm/time-layer-2026-10-25', uuid5.URL)
const uid = (...parts) => uuid5(parts.join('/'), NS)
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const jq = (o) => q(JSON.stringify(o)) + '::jsonb'
const sqlOrNull = (v) => (v === null || v === undefined ? 'NULL' : q(v))

const PROJECTS = {
  'bio-core-lpm-synth': '28997544-0d87-4b05-9ee2-7c474513c108',
  'interdisciplinary-lpm-synth': '371fce26-d1f3-439b-95df-0a0e38b8a824',
}
const SHARE = { low: 0.1, high: 0.3 }

const lines = []
const w = (s = '') => lines.push(s)
const fx = { plans: [], placements: [], assumptions: [] }

w(`-- Sequenced starter plans for bio-core-lpm-synth and interdisciplinary-lpm-synth.
-- Generated by scripts/generate_sequenced_plans_migration.mjs; do not hand-edit.
--
-- Migration 176's starter plans place every stage of a grade band across the same years, so they leave the order of
-- stages inside a band open. These two plans give each stage its own stretch of the band in dependency order, which
-- lets the Time page's order checks say something about the space's own prerequisite claims. The second plan reverses
-- the order and is a negative control for those checks. It is not a design.
-- Everything here is AI-drafted, status 'proposed', and every hour figure is a placeholder.

SET search_path = public, extensions;
`)

for (const [slug, pid] of Object.entries(PROJECTS)) {
  const objs = await rest(`lpm_data_objects?select=id,object_type,title,grade_band,content,status&project_id=eq.${pid}&limit=1000`)
  const type = new Map(objs.map((o) => [o.id, o.object_type]))
  const stages = objs.filter((o) => o.object_type === 'substrand' && o.status === 'accepted').map((r) => ({
    id: r.id, title: r.title, band: r.grade_band, strand: r.content?._source?.path ?? 'strand',
    concepts: (r.content?.concepts ?? []).map((c) => ({ id: c.id, emphasis: c.emphasis })),
    outcomes: (r.content?.performanceIndicators ?? []).length, required: r.content?.required !== false,
  })).sort((a, b) => a.id.localeCompare(b.id))
  const conns = await rest(`lpm_connections?select=relation_type,from_object_id,to_object_id,status&project_id=eq.${pid}&limit=1000`)
  const sources = { stageStrand: {}, strandEdges: [], stageEdges: [], threads: [] }
  for (const c of conns) {
    if (c.status !== 'accepted') continue
    const a = type.get(c.from_object_id)
    const b = type.get(c.to_object_id)
    if (c.relation_type === 'isChildOf' && a === 'substrand' && b === 'strand') sources.stageStrand[c.from_object_id] = c.to_object_id
    else if (c.relation_type === 'prerequisiteOf' || c.relation_type === 'foundationalTo') {
      if (a === 'strand' && b === 'strand') sources.strandEdges.push({ from: c.from_object_id, to: c.to_object_id, relation: c.relation_type })
      else if (a === 'substrand' && b === 'substrand') sources.stageEdges.push({ from: c.from_object_id, to: c.to_object_id, relation: c.relation_type })
    }
  }
  const threads = await rest(`lpm_threads?select=id,slug,title,status&project_id=eq.${pid}&status=eq.accepted&limit=100`)
  for (const t of threads) {
    const st = await rest(`lpm_thread_stations?select=data_object_id,sequence&thread_id=eq.${t.id}&order=sequence`)
    sources.threads.push({ id: t.id, slug: t.slug, title: t.title, stageIds: st.map((s) => s.data_object_id) })
  }
  const bands = T.BAND_NAMES
  const edges = T.deriveOrderEdges(sources, stages, bands)
  const axis1 = uid('axis', pid, 'k12-tiers')

  w(`-- ${slug}: ${stages.length} stages, ${edges.length} ordering claims`)
  const plans = [
    { key: 'sequenced', order: 'dependency', name: 'Starter plan: stages in sequence, in dependency order', summary: 'Inside each grade band every stage takes its own stretch of the band, in the order the space\'s prerequisite and thread links give. Placeholder numbers. It shows a shape and makes no recommendation.' },
    { key: 'sequenced-reverse', order: 'reverse', name: 'Control: the same sequence in reverse dependency order', summary: 'A negative control for the order check. It reverses the sequence on purpose so that the check has violations to find. It is not a design.' },
  ]
  const planIds = []
  for (const pl of plans) {
    const planId = uid('plan', pid, pl.key)
    planIds.push(planId)
    const params = { preset: 'sequenced', share: SHARE, sequence_order: pl.order, reinforcing_share: 0.15 }
    fx.plans.push({ id: planId, project_id: pid, axis_id: axis1, name: pl.name, summary: pl.summary, kind: 'planned', parameters: params, forked_from: null, valid_from: null, valid_to: null, status: 'proposed', created_at: '2026-10-25T00:02:00Z' })
    w('INSERT INTO lpm_time_plans (id, project_id, axis_id, name, summary, kind, parameters, status)')
    w(`VALUES (${q(planId)}, ${q(pid)}, ${q(axis1)}, ${q(pl.name)}, ${q(pl.summary)}, 'planned', ${jq(params)}, 'proposed') ON CONFLICT (id) DO NOTHING;`)
    T.generateStarterPlacements(stages, params, bands, edges).forEach((p, i) => {
      fx.placements.push({ id: uid('placement', planId, String(i)), plan_id: planId, ...p, sort_order: i })
      w('INSERT INTO lpm_time_placements (id, plan_id, target_type, target_id, role, resource, selector, amount, note, sort_order)')
      w(`VALUES (${q(uid('placement', planId, String(i)))}, ${q(planId)}, ${q(p.target_type)}, ${q(p.target_id)}, ${q(p.role)}, ${q(p.resource)}, ${jq(p.selector)}, ${jq(p.amount)}, ${sqlOrNull(p.note)}, ${i}) ON CONFLICT (id) DO NOTHING;`)
    })
  }
  const assumptions = [
    [planIds[0], 'Inside a band, each stage takes its own stretch of the band\'s teaching time, in dependency order. Stages with no dependency between them are ordered by strand and then by id.', 'derived', 'low', 'Design note 2026-10-25, section 5.11 (order checks).', 'The prerequisite and foundational links between strands apply inside each grade band. This is a rule of the model and makes no claim about how any school should sequence.'],
    [planIds[1], 'This plan reverses the dependency order on purpose. It is a negative control for the order check and carries no design intent.', 'derived', 'high', 'Design note 2026-10-25, section 5.11.', 'A check that never reports a violation tells us little. The control shows what a violation looks like on this space.'],
  ]
  assumptions.forEach(([planId, statement, type, conf, src, why], i) => {
    fx.assumptions.push({ id: uid('assumption', pid, `seq-${i}`), project_id: pid, plan_id: planId, axis_id: null, projection_id: null, statement, assumption_type: type, confidence: conf, source: src, rationale: why, value: null, status: 'open' })
    w('INSERT INTO lpm_time_assumptions (id, project_id, plan_id, axis_id, projection_id, statement, assumption_type, confidence, source, rationale, value)')
    w(`VALUES (${q(uid('assumption', pid, `seq-${i}`))}, ${q(pid)}, ${q(planId)}, NULL, NULL, ${q(statement)}, ${q(type)}, ${q(conf)}, ${q(src)}, ${q(why)}, NULL) ON CONFLICT (id) DO NOTHING;`)
  })
  w()
}

const fxIdx = process.argv.indexOf('--fixtures')
if (fxIdx > -1) {
  const { writeFileSync } = await import('node:fs')
  writeFileSync(process.argv[fxIdx + 1], JSON.stringify(fx))
  process.stderr.write(`Wrote fixtures to ${process.argv[fxIdx + 1]}\n`)
}
process.stdout.write(lines.join('\n') + '\n')
